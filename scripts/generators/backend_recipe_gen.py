#!/usr/bin/env python3
"""One generic table-driven backend recipe/builder/projection generator.

The single generator for the backend TableGen outputs, selected by
`--profile` (`solidity-recipe-adapter`, `solidity-emit-builders`,
`solidity-projection`, `postgres-recipe-adapter`,
`postgres-recipe-builders`, `postgres-projection`). It is the canonical
producer identity — the CMake pipelines, the Makefile regen target, the census,
and the freshness tests invoke it directly (the R2a compatibility wrappers were
retired in R2b), and every generated `.inc` names this generator + its profile in
its `GENERATED by` header. Every profile runs the pinned `llvm-tblgen --dump-json`
over a backend `.td`, walks the declared builder/factory tables, and emits
deterministic C++.

Shared core (used by all four profiles): the tblgen loader (`load_records`),
record `deref`/name/field access, dense-index + signature helpers, and
per-profile provenance. The two homologous `<backend>BuildNode` recipe adapters
lower their `.td` into ONE normalized adapter IR (`AdapterNode`) and run through
ONE dispatch-arm engine (`emit_adapter_dispatcher`): the shared traversal, guard
framing, operand binding, fallthrough, and output. Each adapter supplies only a
small arm-body callback for its backend emission action — PostgreSQL's is
declarative data (`PG_ADAPTER_ARMS`), Solidity's is its `.td`-declared transform
schema. The PostgreSQL factory-builder and Solidity emit-builder emit
structurally distinct artifacts (a factory switch; signature decl/def); they keep
their own small emitters but consume the same shared loader/validation/signature
core — no duplicated parsing pipeline remains.

Provenance is per-profile: `sha256(shared engine source + that profile's own
source/data + that backend's .td)`. An unrelated profile edit leaves the other
backend's committed `.inc` byte-identical; a shared-core edit re-stamps all.
Byte-identity across the extraction is preserved — every emitted line is
unchanged; the only committed delta is the self-hashers' one-line `Source-SHA256`
re-bind. R2b repoints the two backend CMake pipelines directly at this generator
and deletes the wrappers.
"""
