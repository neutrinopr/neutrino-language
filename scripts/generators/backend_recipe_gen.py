# ---------------------------------------------------------------------
# Shared machinery used by every profile: tblgen load, record helpers,
# and per-profile provenance. Provenance binds ONLY the shared engine
# source + the selected profile's own source/data + that backend's .td —
# never the whole combined file — so editing one backend's profile leaves
# every other backend's committed .inc byte-identical ( P1b).
# ---------------------------------------------------------------------
def cpp(value):
    return json.dumps(value)


def load_records(td, includes, tblgen):
    command = [tblgen, "--dump-json"]
    for include in includes:
        command += ["-I", include]
    command.append(td)
    return json.loads(subprocess.check_output(command, text=True))


def deref(d, ref):
    if isinstance(ref, dict) and ref.get("kind") == "def":
        return d[ref["def"]]
    return ref


def record_name(value):
    return value["def"] if isinstance(value, dict) else value


def record_field(record, name, default=None):
    """Read an llvm-tblgen record field, never an admitted L2 schema object."""
    return record[name] if name in record else default


def require_dense(indices, count):
    """Shared dense-index invariant: indices are exactly 0..count-1."""
    return sorted(indices) == list(range(count))


def signature_join_incremental(opening, pieces, suffix):
    """Shared 80-column signature fill (incremental): pack parameters onto the
    open line while they fit, else align under the opening."""
    if not pieces:
        return opening + suffix
    out = opening
    indent = " " * len(opening)
    for index, piece in enumerate(pieces):
        trailer = "," if index + 1 < len(pieces) else suffix
        candidate = piece + trailer
        if index and len(out.rsplit("\n", 1)[-1]) + 1 + len(candidate) <= 80:
            out += " " + candidate
        elif not index and len(out) + len(candidate) <= 80:
            out += candidate
        else:
            if index:
                out += "\n"
            out += indent + candidate
    return out


def signature_lines_atomic(prefix, params, suffix):
    """Shared 80-column signature fill (all-or-nothing): one line if it fits,
    else every parameter on its own indented line."""
    one_line = f"{prefix}({', '.join(params)}){suffix}"
    if len(one_line) <= 80:
        return [one_line]
    return [prefix + "(", "    " + ",\n    ".join(params) + ")" + suffix]


# The shared engine surface whose source is bound into EVERY profile's
# provenance (a change here legitimately re-stamps all profiles). Resolved by
# name at call time so it can include shared helpers defined later in the file.
_ENGINE_SURFACE_NAMES = (
    "profile_source_sha256",
    "cpp", "load_records", "deref", "record_name", "record_field",
    "require_dense", "signature_join_incremental", "signature_lines_atomic",
    "AdapterNode", "lower_adapter_nodes", "classify_operands",
    "emit_operand_binds", "emit_adapter_dispatcher",
)


def _engine_source():
    g = globals()
    return "\0".join(inspect.getsource(g[name]) for name in _ENGINE_SURFACE_NAMES)


def profile_source_sha256(profile_objs, td_paths):
    """Freshness digest = shared engine source + this profile's own
    source/data + its .td inputs. Decoupled per profile ( P1b)."""
    h = hashlib.sha256()
    h.update(_engine_source().encode("utf-8"))
    h.update(b"\0")
    for obj in profile_objs:
        text = inspect.getsource(obj) if callable(obj) else repr(obj)
        h.update(text.encode("utf-8"))
        h.update(b"\0")
    for path in td_paths:
        h.update(pathlib.Path(path).read_bytes())
        h.update(b"\0")
    return h.hexdigest()


