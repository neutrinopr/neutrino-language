# =====================================================================
# Profile: solidity-emit-builders
# (the typed SolStmt
# Emit builder declarations + definitions)
# =====================================================================
def solidity_emit_builders_generate(td, includes, tblgen):
    """Return the (declarations, definitions) include text deterministically."""
    def cpp_type(arg):
        if arg["kind"] == "scalar":
            return "std::string"
        if arg["kind"] == "list":
            return "std::vector<SolParam>"
        if arg["kind"] == "body":
            return "std::vector<SolStmt>"
        if arg["kind"] == "comment":
            return "std::string"
        if arg["kind"] == "enum":
            return (
                f"std::vector<{arg['cppType']}>"
                if arg["repeated"]
                else arg["cppType"]
            )
        raise AssertionError(arg)

    def format_signature(prefix, name, args, suffix):
        pieces = [f"{cpp_type(arg)} {arg['name']}" for arg in args]
        return signature_join_incremental(f"{prefix}{name}(", pieces, suffix)

    def load_nodes():
        version = subprocess.run(
            [tblgen, "--version"], capture_output=True, text=True
        )
        if version.returncode or not re.search(r"LLVM version 15\.", version.stdout):
            raise SystemExit(
                "gen_emit_builders: --tblgen must be the pinned LLVM 15.x tool"
            )
        command = [tblgen, "--dump-json"]
        for include in includes:
            command += ["-I", include]
        command.append(td)
        result = subprocess.run(command, capture_output=True, text=True)
        if result.returncode:
            raise SystemExit("llvm-tblgen failed:\n" + result.stderr)
        data = json.loads(result.stdout)
        nodes = []
        for record in data.get("!instanceof", {}).get("TargetPrinterNode", []):
            row = data[record]
            if row.get("Target") != "solidity" or row.get("Model") != "SolStmt":
                continue
            builder = str(row.get("BuilderName", ""))
            if not builder:
                continue

            args_by_name = {}
            scalar_indexes = {}
            for field_ref in row.get("Fields", []):
                field = data[record_name(field_ref)]
                name = str(field["Name"])
                index = int(field["Index"])
                if name in args_by_name:
                    raise SystemExit(f"{record}: duplicate builder input {name}")
                if index in scalar_indexes:
                    raise SystemExit(
                        f"{record}: duplicate scalar operand index {index}"
                    )
                args_by_name[name] = {
                    "name": name,
                    "kind": "scalar",
                    "index": index,
                }
                scalar_indexes[index] = name
            if scalar_indexes and not require_dense(
                    scalar_indexes, max(scalar_indexes) + 1):
                raise SystemExit(f"{record}: scalar operand indexes are not dense")

            for enum_ref in row.get("EnumFields", []):
                enum_field = data[record_name(enum_ref)]
                name = str(enum_field["Name"])
                spelling = data[record_name(enum_field["Spelling"])]
                if name in args_by_name:
                    raise SystemExit(f"{record}: duplicate builder input {name}")
                args_by_name[name] = {
                    "name": name,
                    "kind": "enum",
                    "cppType": str(spelling["CppType"]),
                    "repeated": bool(int(enum_field["Repeated"])),
                }

            list_field = str(row.get("ListField", ""))
            if list_field:
                if list_field in args_by_name:
                    raise SystemExit(
                        f"{record}: repeated input shadows {list_field}"
                    )
                args_by_name[list_field] = {
                    "name": list_field,
                    "kind": "list",
                }

            comment_field = str(row.get("CommentField", ""))
            if comment_field:
                if comment_field in args_by_name:
                    raise SystemExit(
                        f"{record}: comment input shadows {comment_field}"
                    )
                args_by_name[comment_field] = {
                    "name": comment_field,
                    "kind": "comment",
                }

            optional_body = bool(int(row.get("BuilderBodyOptional", 0)))
            if not bool(int(row["IsLeaf"])) and not optional_body:
                args_by_name["body"] = {
                    "name": "body",
                    "kind": "body",
                }
            elif bool(int(row["IsLeaf"])) and optional_body:
                raise SystemExit(
                    f"{record}: leaf builder cannot have an optional body"
                )

            order = [str(value) for value in row.get("BuilderOrder", [])]
            if len(order) != len(set(order)):
                raise SystemExit(f"{record}: duplicate BuilderOrder entry")
            missing = sorted(set(args_by_name) - set(order))
            extra = sorted(set(order) - set(args_by_name))
            if missing or extra:
                raise SystemExit(
                    f"{record}: BuilderOrder/schema mismatch "
                    f"(missing={missing}, extra={extra})"
                )
            nodes.append(
                {
                    "record": record,
                    "ordinal": int(row["Ordinal"]),
                    "builder": builder,
                    "args": [args_by_name[name] for name in order],
                    "scalars": sorted(
                        (
                            arg
                            for arg in args_by_name.values()
                            if arg["kind"] == "scalar"
                        ),
                        key=lambda arg: arg["index"],
                    ),
                    "enums": [
                        args_by_name[str(data[record_name(ref)]["Name"])]
                        for ref in row.get("EnumFields", [])
                    ],
                    "list": args_by_name.get(list_field) if list_field else None,
                    "body": args_by_name.get("body"),
                    "comment": args_by_name.get(comment_field)
                    if comment_field
                    else None,
                }
            )
        nodes.sort(key=lambda node: node["ordinal"])
        if len(nodes) != 19:
            raise SystemExit(
                f"expected 19 Solidity Emit builders, discovered {len(nodes)}"
            )
        names = [node["builder"] for node in nodes]
        if len(names) != len(set(names)):
            raise SystemExit("duplicate Solidity Emit builder name")
        return nodes

    def generated_header(source_digest):
        return (
            "// GENERATED by scripts/generators/backend_recipe_gen.py "
            "--profile solidity-emit-builders -- DO NOT EDIT.\n"
            f"// Source-SHA256: {source_digest}\n"
        )

    def generate_declarations(nodes, digest):
        lines = [
            generated_header(digest).rstrip(),
            "  const std::string &operand(std::size_t index) const {",
            "    static const std::string kEmpty;",
            "    return index < operands.size() ? operands[index] : kEmpty;",
            "  }",
            "",
        ]
        for node in nodes:
            lines.append(
                format_signature(
                    "  static SolStmt ",
                    node["builder"],
                    node["args"],
                    ");",
                )
            )
        return "\n".join(lines) + "\n"

    def generate_definitions(nodes, digest):
        lines = [generated_header(digest).rstrip()]
        for node in nodes:
            lines += [
                format_signature(
                    "SolStmt SolStmt::", node["builder"], node["args"], ") {"
                )
            ]
            if node["scalars"]:
                lines.append(
                    f"  std::vector<std::string> operands({len(node['scalars'])});"
                )
                for scalar in node["scalars"]:
                    lines.append(
                        f"  operands[{scalar['index']}] = "
                        f"std::move({scalar['name']});"
                    )
            else:
                lines.append("  std::vector<std::string> operands;")

            if node["list"]:
                name = node["list"]["name"]
                lines.append(
                    "  std::vector<std::vector<std::string>> group ="
                )
                lines.append(
                    f'      projectGeneratedParams({name}, "SolStmt::'
                    f'{node["builder"]}");'
                )
            else:
                lines.append("  std::vector<std::vector<std::string>> group;")

            if node["enums"]:
                lines.append(
                    "  std::vector<std::vector<int>> enumOrdinals;"
                )
                lines.append(
                    f"  enumOrdinals.reserve({len(node['enums'])});"
                )
                for enum in node["enums"]:
                    name = enum["name"]
                    if enum["repeated"]:
                        lines.append(
                            "  enumOrdinals.push_back("
                            f"projectGeneratedEnumOrdinals({name}));"
                        )
                    else:
                        lines.append(
                            "  enumOrdinals.push_back("
                            f"{{static_cast<int>({name})}});"
                        )
            else:
                lines.append("  std::vector<std::vector<int>> enumOrdinals;")

            body = node["body"]["name"] if node["body"] else None
            comment = node["comment"]["name"] if node["comment"] else None
            lines += [
                f"  validateGeneratedSolStmt(SolStmt::Kind::{node['record']},",
                (
                    f"                           operands, {body}, group,"
                    if body
                    else "                           operands, {}, group,"
                ),
                "                           enumOrdinals);",
                f"  return SolStmt(SolStmt::Kind::{node['record']},",
                "                 std::move(operands),",
                (
                    f"                 std::move({body}),"
                    if body
                    else "                 {},"
                ),
                (
                    "                 std::move(group), std::move(enumOrdinals),"
                    if comment
                    else "                 std::move(group), std::move(enumOrdinals));"
                ),
            ]
            if comment:
                lines.append(f"                 std::move({comment}));")
            lines += [
                "}",
                "",
            ]
        return "\n".join(lines)

    nodes = load_nodes()
    digest = profile_source_sha256(
        [solidity_emit_builders_generate], [td])
    return (generate_declarations(nodes, digest),
            generate_definitions(nodes, digest))


def _run_solidity_emit_builders(argv):
    parser = argparse.ArgumentParser()
    parser.add_argument("--td", required=True)
    parser.add_argument("--tblgen", required=True)
    parser.add_argument("-I", action="append", default=[])
    parser.add_argument("--decls", required=True)
    parser.add_argument("--defs", required=True)
    args = parser.parse_args(argv)
    decls, defs = solidity_emit_builders_generate(args.td, args.I, args.tblgen)
    pathlib.Path(args.decls).write_text(decls, encoding="utf-8")
    pathlib.Path(args.defs).write_text(defs, encoding="utf-8")
    return 0


# =====================================================================
# Profile: postgres-recipe-builders
# The  PgStmt factory declarations + generated construction dispatch. A
# structurally distinct artifact (factory switch + emit<Kind> + PgStmt factory
# bodies), so it keeps its own small emitter — but consumes the shared loader
# (`load_records`), `deref`, `require_dense`, and `signature_lines_atomic`; no
# duplicated low-level parsing remains. Text-hashed over its output, so its bytes
# are unchanged. `pgrb_generate` stays module-level with an injectable
# `load_records` for the freshness test's monkeypatch.
# =====================================================================
def pgrb_die(msg):
    sys.stderr.write("gen_pg_recipe_builders: " + msg + "\n")
    sys.exit(1)


def _pgrb_field_name(d, ref):
    field = deref(d, ref)
    name = field.get("Name")
    if not isinstance(name, str) or not name:
        pgrb_die("recipe-builder node has an unnamed scalar field")
    return name


def _pgrb_def_name(d, marker):
    ref = d[marker]["Node"]
    if isinstance(ref, dict) and ref.get("kind") == "def":
        return ref["def"]
    pgrb_die("RecipeBuilderNode.Node is not a def reference")


def _pgrb_node_shape(d, marker):
    node = deref(d, d[marker]["Node"])
    kind = _pgrb_def_name(d, marker)
    section_role = d[marker].get("SectionRole", "")
    if not isinstance(section_role, str):
        pgrb_die(f"{kind}: SectionRole must be a string")
    scalar_fields = [_pgrb_field_name(d, ref) for ref in node["Fields"]]
    list_field = node.get("ListField", "")
    item_fields = node.get("ItemFields", [])
    has_group = bool(list_field or item_fields)
    group_name = list_field if list_field else "items"
    has_body = not bool(node["IsLeaf"])
    if has_body and node.get("Layout") not in ("block", "flat-block"):
        pgrb_die(f"{kind}: non-leaf recipe builder requires block layout")
    return {
        "ordinal": node["Ordinal"],
        "kind": kind,
        "scalars": scalar_fields,
        "has_body": has_body,
        "has_group": has_group,
        "group_name": group_name,
        "section_role": section_role,
    }


def _pgrb_factory_shape(d, marker):
    marker_record = d[marker]
    node = deref(d, marker_record["Node"])
    kind = _pgrb_def_name(d, marker)
    factory = marker_record.get("Factory")
    if not isinstance(factory, str) or not re.fullmatch(
            r"[A-Za-z_][A-Za-z0-9_]*", factory or ""):
        pgrb_die(f"{kind}: invalid RecipeFactoryNode.Factory {factory!r}")
    args = []
    seen_names = set()
    seen_storage = set()
    indexed_args = {"parts": [], "operands": []}
    for ref in marker_record.get("Args", []):
        arg = deref(d, ref)
        name = arg.get("Name")
        cpp_type = arg.get("CppType")
        storage = arg.get("Storage")
        optional_empty = bool(arg.get("OptionalEmpty"))
        part_ordinal = arg.get("PartOrdinal", -1)
        operand_ordinal = arg.get("OperandOrdinal", -1)
        true_literal = arg.get("TrueLiteral", "")
        false_literal = arg.get("FalseLiteral", "")
        fixed_literal = arg.get("FixedLiteral", "")
        if not isinstance(name, str) or not re.fullmatch(
                r"[A-Za-z_][A-Za-z0-9_]*", name or ""):
            pgrb_die(f"{kind}: invalid recipe-factory argument name {name!r}")
        if name in seen_names:
            pgrb_die(f"{kind}: duplicate recipe-factory argument {name}")
        seen_names.add(name)
        if cpp_type not in ("string", "fixed-string", "bool", "stmt-list",
                            "string-groups"):
            pgrb_die(f"{kind}.{name}: unsupported recipe-factory type {cpp_type!r}")
        if storage not in ("text", "aux", "aux2", "flag", "parts",
                           "operands", "body", "group"):
            pgrb_die(f"{kind}.{name}: unsupported PgStmt storage slot {storage!r}")
        if storage not in indexed_args and storage in seen_storage:
            pgrb_die(f"{kind}: duplicate recipe-factory storage slot {storage}")
        seen_storage.add(storage)
        if storage == "parts":
            if cpp_type != "string":
                pgrb_die(f"{kind}.{name}: parts carrier requires string")
            if not isinstance(part_ordinal, int) or part_ordinal < 0:
                pgrb_die(f"{kind}.{name}: parts carrier requires a non-negative "
                         "PartOrdinal")
        elif part_ordinal != -1:
            pgrb_die(f"{kind}.{name}: PartOrdinal is valid only for parts carrier")
        if storage == "operands":
            if cpp_type not in ("string", "fixed-string", "bool"):
                pgrb_die(f"{kind}.{name}: operands carrier requires string, "
                         "fixed-string, or bool")
            if not isinstance(operand_ordinal, int) or operand_ordinal < 0:
                pgrb_die(f"{kind}.{name}: operands carrier requires a non-negative "
                         "OperandOrdinal")
        elif operand_ordinal != -1:
            pgrb_die(f"{kind}.{name}: OperandOrdinal is valid only for operands "
                     "carrier")
        if storage == "flag" and cpp_type != "bool":
            pgrb_die(f"{kind}.{name}: flag requires bool")
        if storage in ("text", "aux", "aux2") and cpp_type != "string":
            pgrb_die(f"{kind}.{name}: {storage} requires string")
        if storage == "body" and cpp_type != "stmt-list":
            pgrb_die(f"{kind}.{name}: body requires stmt-list")
        if storage == "group" and cpp_type != "string-groups":
            pgrb_die(f"{kind}.{name}: group requires string-groups")
        if cpp_type == "bool" and storage not in ("flag", "operands"):
            pgrb_die(f"{kind}.{name}: bool requires flag or operands")
        if cpp_type == "stmt-list" and storage != "body":
            pgrb_die(f"{kind}.{name}: stmt-list requires body")
        if cpp_type == "string-groups" and storage != "group":
            pgrb_die(f"{kind}.{name}: string-groups requires group")
        has_literals = bool(true_literal or false_literal)
        if cpp_type == "bool" and storage == "operands":
            if not true_literal or not false_literal:
                pgrb_die(f"{kind}.{name}: bool operand requires closed true/false "
                         "literals")
            if true_literal == false_literal:
                pgrb_die(f"{kind}.{name}: bool operand literals must differ")
        elif has_literals:
            pgrb_die(f"{kind}.{name}: literal mapping is valid only for bool "
                     "operands")
        if cpp_type == "fixed-string":
            if storage != "operands":
                pgrb_die(f"{kind}.{name}: fixed-string requires operands")
            if not fixed_literal:
                pgrb_die(f"{kind}.{name}: fixed-string requires a non-empty "
                         "FixedLiteral")
        elif fixed_literal:
            pgrb_die(f"{kind}.{name}: FixedLiteral is valid only for "
                     "fixed-string operands")
        if optional_empty and cpp_type != "string":
            pgrb_die(f"{kind}.{name}: optional-empty is valid only for string")
        row = {
            "name": name,
            "type": cpp_type,
            "storage": storage,
            "optional_empty": optional_empty,
            "part_ordinal": part_ordinal,
            "operand_ordinal": operand_ordinal,
            "true_literal": true_literal,
            "false_literal": false_literal,
            "fixed_literal": fixed_literal,
        }
        args.append(row)
        if storage in indexed_args:
            indexed_args[storage].append(row)
    for storage, carrier_args in indexed_args.items():
        if not carrier_args:
            continue
        ordinal_key = "part_ordinal" if storage == "parts" \
            else "operand_ordinal"
        ordinals = [arg[ordinal_key] for arg in carrier_args]
        if len(set(ordinals)) != len(ordinals):
            duplicate = next(
                ordinal for ordinal in ordinals if ordinals.count(ordinal) > 1)
            pgrb_die(f"{kind}: duplicate recipe-factory {storage[:-1]} ordinal "
                     f"{duplicate}")
        if not require_dense(ordinals, len(carrier_args)):
            pgrb_die(f"{kind}: recipe-factory {storage} ordinals must be dense "
                     f"0..{len(carrier_args) - 1}")
    has_body_arg = any(arg["storage"] == "body" for arg in args)
    if bool(node["IsLeaf"]) and has_body_arg:
        pgrb_die(f"{kind}: leaf node cannot accept a factory body")
    if not bool(node["IsLeaf"]) and not has_body_arg:
        pgrb_die(f"{kind}: non-leaf node requires one typed factory body")
    operand_count = len(indexed_args["operands"])
    if operand_count != len(node["Fields"]):
        pgrb_die(f"{kind}: factory operand count {operand_count} does not match "
                 f"node field count {len(node['Fields'])}")
    has_group_arg = any(arg["storage"] == "group" for arg in args)
    node_has_group = bool(node.get("ListField") or node.get("ItemFields"))
    if has_group_arg != node_has_group:
        expected = "one repeated group" if node_has_group else "no group"
        pgrb_die(f"{kind}: node shape requires {expected} factory argument")
    return {
        "ordinal": node["Ordinal"],
        "kind": kind,
        "factory": factory,
        "args": args,
    }


PGRB_HEADER = ("// GENERATED by scripts/generators/backend_recipe_gen.py --profile "
               "postgres-recipe-builders -- DO NOT EDIT.\n// Source: "
               "PostgresTargetNodes.td (). Regenerate; do not hand-edit.\n")


def _pgrb_cpp_param(arg, *, declaration):
    cpp_type = {
        "string": "std::string",
        "bool": "bool",
        "stmt-list": "std::vector<PgStmt>",
        "string-groups": "std::vector<std::vector<std::string>>",
    }[arg["type"]]
    default = ' = ""' if declaration and arg["optional_empty"] else ""
    return f"{cpp_type} {arg['name']}{default}"


def _pgrb_public_args(factory):
    """Factory parameters supplied by callers.

    fixed-string operands are closed target-shape atoms emitted by the
    generated builder itself, so exposing them as caller parameters would
    recreate an authoring/decision seam.
    """
    return [arg for arg in factory["args"] if arg["type"] != "fixed-string"]


def _pgrb_emit_decl(factories):
    # Included in PgStmt's public section. The friend preserves the private
    # constructor seal for the optional recipe dispatch; the static declarations
    # are generated from the same TableGen factory schema as their definitions.
    lines = [PGRB_HEADER.rstrip("\n"), "friend struct GeneratedRecipeBuilder;"]
    for factory in factories:
        params = [
            _pgrb_cpp_param(arg, declaration=True)
            for arg in _pgrb_public_args(factory)]
        lines += signature_lines_atomic(
            f"static PgStmt {factory['factory']}", params, ";")
    return "\n".join(lines) + "\n"


def _pgrb_emit_def(nodes, renderer_adapters, factories):
    L = [PGRB_HEADER.rstrip("\n"),
         "// The including TU provides PostgresModel.h (complete PgStmt).",
         "namespace neutrino {",
         "namespace postgres_model {",
         "",
         "struct GeneratedRecipeBuildArgs {",
         "  std::vector<PgStmt> body;",
         "  std::vector<std::string> operands;",
         "  std::vector<std::vector<std::string>> group;",
         "};",
         "",
         "// The generated construction dispatch: exact ordinal -> the node's",
         "// schema-derived concrete construction. A generated switch (never a",
         "// handwritten one); an unknown ordinal or malformed carrier fails",
         "// closed. It reaches PgStmt's private ctor () as a declared",
         "// friend.",
         "struct GeneratedRecipeBuilder {",
         "  static std::optional<PgStmt>",
         "  build(unsigned ordinal, GeneratedRecipeBuildArgs args = {}) {",
         "    switch (ordinal) {"]
    for node in nodes:
        ordinal = node["ordinal"]
        kind = node["kind"]
        scalar_count = len(node["scalars"])
        body_check = "false" if node["has_body"] else "!args.body.empty()"
        group_check = "false" if node["has_group"] else "!args.group.empty()"
        L += [
            f"    case {ordinal}u:",
            f"      if ({body_check} || args.operands.size() != "
            f"{scalar_count}u || {group_check})",
            "        return std::nullopt;",
            f"      return PgStmt(PgStmt::Kind::{kind}, {{}}, {{}}, {{}}, "
            "false,",
            "                    std::move(args.body), {}, "
            "std::move(args.operands),",
            "                    std::move(args.group));",
        ]
    L += ["    default:",
          "      return std::nullopt;",
          "    }",
          "  }",
          "};",
          "",
          "// Stable per-node construction entries the renderer calls in place of",
          "// the retired handwritten factories (target-node shapes; a keyed",
          "// recipe that emits them is owned by a later finalized slice)."]
    for node in nodes:
        ordinal = node["ordinal"]
        kind = node["kind"]
        params = [f"std::string {name}" for name in node["scalars"]]
        if node["has_body"]:
            params.append("std::vector<PgStmt> body")
        if node["has_group"]:
            params.append(
                "std::vector<std::vector<std::string>> " + node["group_name"])
        L.append(f"inline std::optional<PgStmt> emit{kind}(")
        if params:
            L.append("    " + ",\n    ".join(params) + ") {")
        else:
            L[-1] += ") {"
        L.append("  GeneratedRecipeBuildArgs args;")
        if node["scalars"]:
            operands = ", ".join(
                f"std::move({name})" for name in node["scalars"])
            L.append(f"  args.operands = {{{operands}}};")
        if node["has_body"]:
            L.append("  args.body = std::move(body);")
        if node["has_group"]:
            L.append(f"  args.group = std::move({node['group_name']});")
        L += [f"  return GeneratedRecipeBuilder::build({ordinal}u, "
              "std::move(args));",
              "}"]
    renderer_lines = []
    # : every PgStmt kind is now a generated printer node (all handwritten
    # renderer adapters are retired), so the recursive tree renderer needs no
    # `pgtext::Seam` — the raw-Line seam is fully collapsed.
    renderer_start = len(L)
    L += [
        "",
        "#ifdef NEUTRINO_PG_DEFINE_RENDERER",
        "// Generic typed-tree traversal: every PgStmt kind is a generated printer",
        "// node. Recipes select and order the complete statements; this renders",
        "// the resulting typed nodes. It is not the recipe-hook ABI.",
        "inline codetext::Node renderPgStmtTree(const PgStmt &stmt) {",
        "  std::vector<codetext::Node> children;",
        "  children.reserve(stmt.body.size());",
        "  for (const PgStmt &child : stmt.body)",
        "    children.push_back(renderPgStmtTree(child));",
        "  if (!generated_printer::hasHandler(stmt.kind))",
        "    llvm::report_fatal_error(",
        '        "postgres printer: target node has no generated handler",',
        "        /*gen_crash_diag=*/false);",
        "  return generated_printer::render(stmt, std::move(children));",
        "}",
        "#endif // NEUTRINO_PG_DEFINE_RENDERER",
    ]
    renderer_lines = L[renderer_start:]
    del L[renderer_start:]
    if factories:
        L += [
            "",
            "// Public typed factory entries generated from RecipeFactoryNode.",
            "// Existing production callers retain their stable API while no",
            "// handwritten PgStmt construction body remains in the header.",
        ]
        for factory in factories:
            params = [
                _pgrb_cpp_param(arg, declaration=False)
                for arg in _pgrb_public_args(factory)]
            storage = {
                "text": "{}",
                "aux": "{}",
                "aux2": "{}",
                "flag": "false",
                "body": "{}",
                "group": "{}",
            }
            parts = []
            operands = []
            for arg in factory["args"]:
                value = arg["name"]
                if arg["type"] == "string":
                    value = f"std::move({value})"
                elif arg["type"] == "fixed-string":
                    value = json.dumps(arg["fixed_literal"])
                elif arg["type"] in ("stmt-list", "string-groups"):
                    value = f"std::move({value})"
                elif arg["type"] == "bool" and arg["storage"] == "operands":
                    value = (
                        f'{value} ? {json.dumps(arg["true_literal"])} : '
                        f'{json.dumps(arg["false_literal"])}')
                if arg["storage"] == "parts":
                    parts.append((arg["part_ordinal"], value))
                elif arg["storage"] == "operands":
                    operands.append((arg["operand_ordinal"], value))
                else:
                    storage[arg["storage"]] = value
            parts = [value for _, value in sorted(parts)]
            operands = [value for _, value in sorted(operands)]
            L += signature_lines_atomic(
                f"inline PgStmt PgStmt::{factory['factory']}", params, " {")
            L.append(
                f"  return PgStmt(Kind::{factory['kind']}, {storage['text']},")
            if parts:
                L += [
                    f"                {storage['aux']}, {storage['aux2']}, "
                    f"{storage['flag']}, {storage['body']},",
                    "                {" + ",\n                 ".join(parts) +
                    "},",
                ]
            else:
                L.append(
                    f"                {storage['aux']}, {storage['aux2']}, "
                    f"{storage['flag']}, {storage['body']}, {{}},")
            if operands:
                L.append("                {" +
                         ",\n                 ".join(operands) + "},")
            else:
                L.append("                {},")
            L.append(f"                {storage['group']});")
            L.append("}")
    L += renderer_lines
    L += ["",
          "} // namespace postgres_model",
          "} // namespace neutrino"]
    text = "\n".join(L) + "\n"
    ghash = hashlib.sha256(text.encode("utf-8")).hexdigest()
    return text + f"// generationHash: {ghash}\n"


def pgrb_generate(td, includes, tblgen, load_records=None):
    """Return the (declaration, definition) include text deterministically.
    `load_records` is resolved from this module at call time when not passed, so
    the freshness test's monkeypatch of `load_records` flows through."""
    if load_records is None:
        load_records = globals()["load_records"]
    d = load_records(td, includes, tblgen)
    io = d.get("!instanceof", {})
    marker_names = sorted(io.get("RecipeBuilderNode", []))
    if not marker_names:
        pgrb_die("no RecipeBuilderNode markers in " + td)

    nodes = []
    seen = set()
    for name in marker_names:
        shape = _pgrb_node_shape(d, name)
        if shape["ordinal"] in seen:
            pgrb_die(f"duplicate recipe-builder ordinal {shape['ordinal']}")
        seen.add(shape["ordinal"])
        nodes.append(shape)
    nodes.sort(key=lambda row: row["ordinal"])
    factories = [
        _pgrb_factory_shape(d, name)
        for name in sorted(io.get("RecipeFactoryNode", []))
    ]
    factories.sort(key=lambda row: row["ordinal"])
    if len({row["ordinal"] for row in factories}) != len(factories):
        pgrb_die("duplicate recipe-factory node ordinal")
    if len({row["factory"] for row in factories}) != len(factories):
        pgrb_die("duplicate generated recipe-factory name")
    renderer_adapters = []
    permitted_storage = {"text", "aux", "aux2", "flag", "parts"}
    for name in sorted(io.get("RecipePrinterAdapterNode", [])):
        marker = d[name]
        shape = _pgrb_node_shape(d, name)
        adapter = marker.get("Adapter")
        if not re.fullmatch(r"[A-Za-z_][A-Za-z0-9_]*", adapter or ""):
            pgrb_die(f"{shape['kind']}: invalid printer adapter {adapter!r}")
        args = []
        for arg_ref in marker.get("Args", []):
            arg = deref(d, arg_ref)
            storage = arg.get("Storage")
            index = int(arg.get("Index", 0))
            if storage not in permitted_storage:
                pgrb_die(f"{shape['kind']}: unsupported printer storage {storage!r}")
            if storage != "parts" and index != 0:
                pgrb_die(f"{shape['kind']}: scalar printer storage has an index")
            if storage == "parts" and index < 0:
                pgrb_die(f"{shape['kind']}: negative printer parts index")
            args.append((storage, index))
        shape["adapter"] = adapter
        shape["adapter_args"] = args
        renderer_adapters.append(shape)
    renderer_adapters.sort(key=lambda row: row["ordinal"])
    if len({node["ordinal"] for node in renderer_adapters}) != \
            len(renderer_adapters):
        pgrb_die("duplicate recipe printer-adapter ordinal")

    return (_pgrb_emit_decl(factories),
            _pgrb_emit_def(nodes, renderer_adapters, factories))


def _run_postgres_recipe_builders(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("--td", required=True)
    ap.add_argument("--tblgen", required=True)
    ap.add_argument("-I", dest="includes", action="append", default=[])
    ap.add_argument("--decl-out", required=True,
                    help="class-body friend declaration include")
    ap.add_argument("--def-out", required=True,
                    help="out-of-line builder definition include")
    args = ap.parse_args(argv)
    decl, definition = pgrb_generate(args.td, args.includes, args.tblgen)
    with open(args.decl_out, "w", encoding="utf-8") as fh:
        fh.write(decl)
    with open(args.def_out, "w", encoding="utf-8") as fh:
        fh.write(definition)
    return 0


PROFILES = {
    "postgres-recipe-adapter": _run_postgres_recipe_adapter,
    "postgres-recipe-builders": _run_postgres_recipe_builders,
    "postgres-projection": _run_postgres_projection,
    "postgres-ddl-builders": _run_postgres_ddl_builders,
    "solidity-recipe-adapter": _run_solidity_recipe_adapter,
    "solidity-projection": _run_solidity_projection,
    "solidity-emit-builders": _run_solidity_emit_builders,
}


def run_profile(name, argv=None):
    if argv is None:
        argv = sys.argv[1:]
    if name not in PROFILES:
        raise SystemExit(f"unknown backend generator profile {name!r}")
    return PROFILES[name](argv)


def main(argv=None):
    if argv is None:
        argv = sys.argv[1:]
    parser = argparse.ArgumentParser(add_help=False)
    parser.add_argument("--profile", required=True, choices=sorted(PROFILES))
    known, rest = parser.parse_known_args(argv)
    return run_profile(known.profile, rest)


if __name__ == "__main__":
    sys.exit(main())
