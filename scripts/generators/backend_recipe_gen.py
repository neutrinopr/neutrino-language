# =====================================================================
# Profile: solidity-projection
# The  R5b generated dispatch resolver that retires the handwritten
# finalized-view trio (project/slotExtent/slotItemOrder) in
# SolidityRecipeProvider.cpp. Each declarative row (SolProjectField /
# SolSlotExtent / SolSlotItemOrder in SolidityProjectionSchema.td) names one
# finite structural accessor over projection::FinalizedProjectionSequence; this
# emitter lowers each to the exact C++ the provider used to spell by hand. The
# resolver reads NO plan/spec/domain field and takes NO decision on backend
# meaning — the only leaf-hook it calls is solidityStatusAtom (). Emitted
# into a namespace nested in solidity_model; the provider forwards to it.
# =====================================================================
SOLIDITY_PROJECTION_HEADER = (
    "// GENERATED by scripts/generators/backend_recipe_gen.py --profile "
    "solidity-projection -- DO NOT EDIT.")


def solidity_projection_generate(td, target_td, includes, tblgen):
    data = load_records(td, includes, tblgen)

    def value_symbol(name):
        return f"solidity_Value_{name}"

    def field_symbol(name):
        return "solidity_Field_" + name.replace(".", "_")

    def slot_symbol(name):
        return f"solidity_Slot_{name}"

    def read_accessor(ref):
        arg = data[record_name(ref)]
        return {
            "kind": str(arg["Kind"]),
            "field": str(arg["Field"]),
            "literal": str(arg["Literal"]),
            "transform": str(arg["Transform"]),
            "fields": [str(value) for value in arg["Fields"]],
        }

    def project_case(field_name, value_name, accessor):
        kind = accessor["kind"]
        value = value_symbol(value_name)
        if kind == "exec-scalar":
            return [f"    return save({value}, "
                    f"sequence.executionIdentity.{accessor['field']});"]
        if kind == "proj-empty":
            return [f"    return save({value}, \"\");"]
        if kind == "proj-size":
            return [f"    return save({value}, std::to_string("
                    f"sequence.{accessor['field']}.size()));"]
        if kind == "status-atom":
            role = accessor["field"]
            return [f"    return save({value}, solidityStatusAtom("
                    f"sequence.{role}.mode, sequence.{role}.role));"]
        if kind == "proj-indexed":
            container = accessor["field"]
            member = accessor["fields"][0]
            access = f"sequence.{container}.at(owner.index).{member}"
            if accessor["transform"] == "to-string":
                access = f"std::to_string({access})"
            return [f"    return save({value}, {access});"]
        if kind == "claim-operand":
            return [
                "    {",
                "      const auto &item = sequence.claimInputs.at(owner.index);",
                f"      return save({value}, "
                "\"claim\\t\" + item.type + \"\\t\" + item.name);",
                "    }",
            ]
        if kind == "proj-indexed-expr":
            container = accessor["field"]
            member = accessor["fields"][0]
            return [f"    return saveValueExpression("
                    f"*sequence.{container}.at(owner.index).{member});"]
        if kind == "conditional-ordinal":
            container = accessor["fields"][0]
            member = accessor["field"]
            return [
                "    {",
                f"      const auto &item = sequence.{container}.at(owner.index);",
                "      const auto &keyParam = sequence.values.instanceKeyParam;",
                "      const bool isKey =",
                "          keyParam.has_value() && "
                "keyParam->ordinal == item.ordinal;",
                f"      return save({value}, isKey ? "
                f"sol_detail::uref(item.{member}) : std::string());",
                "    }",
            ]
        if kind == "proj-posting":
            nav = accessor["literal"]
            member = accessor["field"]
            transform = accessor["transform"]
            lines = ["    {"]
            if nav == "flat":
                lines.append(
                    "      const ::neutrino::projection::"
                    "FinalizedPostingProjection &fp =")
                lines.append("          sequence.postings.at(owner.index);")
            else:  # group
                lines += [
                    "      const auto parent = ::llvm::find_if(",
                    "          ctx, [](const SlotIndex &item) {",
                    "            return item.slot == solidity_Slot_effectGroups;",
                    "          });",
                    "      if (parent == ctx.end())",
                    "        return recipeError(RecipeDiagnostic::InputUnbound,",
                    "                           \"Solidity projected field\");",
                    "      const ::neutrino::projection::"
                    "FinalizedPostingProjection &fp =",
                    "          sequence.effectGroups.at(parent->index)",
                    "              .finalizedPostings.at(owner.index);",
                ]
            if transform == "posting-id":
                leaf = f"fp.posting->{member}"
            elif transform == "direction":
                leaf = "std::to_string(static_cast<unsigned>(fp.direction))"
            elif transform == "string-operand":
                leaf = f"\"string\\t\" + fp.posting->{member}"
            elif transform == "uint-operand":
                leaf = f"\"uint\\t\" + fp.posting->{member}"
            elif transform == "memo":
                leaf = "fp.memo.value()"
            else:
                raise SystemExit(
                    f"{field_name}: unknown posting transform {transform}")
            lines.append(f"      return save({value}, {leaf});")
            lines.append("    }")
            return lines
        if kind == "proj-posting-guard":
            # : the guard CONDITION is a predicate position, so the leaf is
            # saved with ExprCategory::Predicate. The category is read off the
            # already-finalized, target-neutral FinalizedPostingGuardKind — it is
            # never inferred from the node shape, so a Direct posting still has no
            # projectable condition and a predicate leaf that is not a comparison
            # still refuses in the guard emitter.
            return [
                "    {",
                "      const auto parent = ::llvm::find_if(",
                "          ctx, [](const SlotIndex &item) {",
                "            return item.slot == solidity_Slot_effectWithPostings ||",
                "                   item.slot == "
                "solidity_Slot_effectWithoutPostings;",
                "          });",
                "      if (parent == ctx.end())",
                "        return recipeError(RecipeDiagnostic::InputUnbound,",
                "                           \"effectful posting guard parent\");",
                "      const auto &posting = sequence.postings.at(parent->index);",
                "      switch (posting.guardKind) {",
                "      case ::neutrino::projection::"
                "FinalizedPostingGuardKind::Comparison:",
                "        if (!posting.comparisonGuard)",
                "          break;",
                "        return savePredicateExpression(*posting.comparisonGuard);",
                "      case ::neutrino::projection::"
                "FinalizedPostingGuardKind::Direct:",
                "        break;",
                "      }",
                "      return recipeError(RecipeDiagnostic::InputUnbound,",
                "                         "
                "\"effectful posting guard expression\");",
                "    }",
            ]
        raise SystemExit(f"{field_name}: unknown projection accessor kind {kind}")

    project_lines = []
    for record in data["!instanceof"].get("SolProjectField", []):
        row = data[record]
        field_name = str(row["Field"])
        value_name = str(row["Value"])
        accessor = read_accessor(row["Accessor"])
        project_lines.append(f"  case {field_symbol(field_name)}:")
        project_lines += project_case(field_name, value_name, accessor)

    # slotExtent: group the value-identical arms behind shared case labels.
    extent_rows = [data[record]
                   for record in data["!instanceof"].get("SolSlotExtent", [])]
    const_one = []
    attest_single = []
    attest_none = []
    size_by_container = {}
    group_postings_size = None
    for row in extent_rows:
        slot = str(row["Slot"])
        kind = str(row["Kind"])
        container = str(row["Container"])
        if kind == "const-one":
            const_one.append(slot)
        elif kind == "attest-single":
            attest_single.append(slot)
        elif kind == "attest-none":
            attest_none.append(slot)
        elif kind == "vector-size":
            size_by_container.setdefault(container, []).append(slot)
        elif kind == "group-postings-size":
            group_postings_size = slot
        else:
            raise SystemExit(f"{slot}: unknown slot-extent kind {kind}")

    def labels(slots):
        return [f"  case {slot_symbol(slot)}:" for slot in slots]

    extent_lines = []
    if const_one:
        extent_lines += labels(const_one) + ["    return 1u;"]
    if attest_single:
        extent_lines += labels(attest_single) + [
            "    return sequence.attestationKind ==",
            "                   ::neutrino::projection::"
            "FinalizedAttestationKind::Single",
            "               ? 1u",
            "               : 0u;",
        ]
    if attest_none:
        extent_lines += labels(attest_none) + [
            "    return sequence.attestationKind ==",
            "                   ::neutrino::projection::"
            "FinalizedAttestationKind::None",
            "               ? 1u",
            "               : 0u;",
        ]
    for container in sorted(size_by_container):
        extent_lines += labels(size_by_container[container]) + [
            f"    return static_cast<unsigned>(sequence.{container}.size());"]
    if group_postings_size is not None:
        extent_lines += [
            f"  case {slot_symbol(group_postings_size)}: {{",
            "    const auto parent = ::llvm::find_if(",
            "        ctx, [](const SlotIndex &item) {",
            "          return item.slot == solidity_Slot_effectGroups;",
            "        });",
            "    if (parent == ctx.end() || "
            "parent->index >= sequence.effectGroups.size())",
            "      return recipeError(RecipeDiagnostic::InputUnbound,",
            "                         \"temporal posting parent\");",
            "    return static_cast<unsigned>(",
            "        sequence.effectGroups[parent->index]"
            ".finalizedPostings.size());",
            "  }",
        ]

    # slotItemOrder: at-ordinal grouped by container, identity grouped, and the
    # two-level group-postings navigation.
    order_rows = [data[record]
                  for record in data["!instanceof"].get("SolSlotItemOrder", [])]
    at_ordinal = {}
    identity = []
    group_postings_order = None
    for row in order_rows:
        slot = str(row["Slot"])
        kind = str(row["Kind"])
        container = str(row["Container"])
        if kind == "at-ordinal":
            at_ordinal.setdefault(container, []).append(slot)
        elif kind == "identity":
            identity.append(slot)
        elif kind == "group-postings-ordinal":
            group_postings_order = slot
        else:
            raise SystemExit(f"{slot}: unknown slot-order kind {kind}")

    order_lines = []
    for container in sorted(at_ordinal):
        order_lines += labels(at_ordinal[container]) + [
            f"    return sequence.{container}.at(index).ordinal;"]
    if identity:
        order_lines += labels(identity) + ["    return index;"]
    if group_postings_order is not None:
        order_lines += [
            f"  case {slot_symbol(group_postings_order)}: {{",
            "    const auto parent = ::llvm::find_if(",
            "        ctx, [](const SlotIndex &item) {",
            "          return item.slot == solidity_Slot_effectGroups;",
            "        });",
            "    if (parent != ctx.end())",
            "      return sequence.effectGroups.at(parent->index)",
            "          .finalizedPostings.at(index).ordinal;",
            "    break;",
            "  }",
        ]

    digest = profile_source_sha256(
        [solidity_projection_generate], [td, target_td])
    lines = [
        SOLIDITY_PROJECTION_HEADER,
        f"// Source-SHA256: {digest}",
        "// The including TU provides SolidityRecipeProvider.cpp state (the "
        "generated",
        "// solidity_recipes.inc constants/helpers + SolidityTargetAdapter.h "
        "leaf-hook).",
        "namespace neutrino {",
        "namespace solidity_model {",
        "namespace generated_projection {",
        "",
        "// project(): map one finalized field id to its structural accessor.",
        "inline ::llvm::Expected<TypedHookInput> solidityProjectField(",
        "    std::vector<std::string> &finalizedValues,",
        "    std::vector<::neutrino::CategorizedExpr> &finalizedExpressions,",
        "    const ::neutrino::projection::FinalizedProjectionSequence &sequence,",
        "    FinalizedFieldId field, ::llvm::ArrayRef<SlotIndex> ctx,",
        "    SlotIndex owner) {",
        "  auto save = [&](FinalizedValueTypeId type,",
        "                  std::string value) -> TypedHookInput {",
        "    const auto ordinal = finalizedValues.size();",
        "    finalizedValues.push_back(std::move(value));",
        "    finalizedExpressions.push_back({});",
        "    return TypedHookInput{type, ordinal};",
        "  };",
        "  // : an expression leaf is saved WITH the category of the position",
        "  // it was projected for; the lowering never re-derives it from the node.",
        "  auto saveExpression =",
        "      [&](const ::neutrino::ExprNode &expression,",
        "          ::neutrino::ExprCategory category) -> TypedHookInput {",
        "    const auto ordinal = finalizedValues.size();",
        "    finalizedValues.emplace_back();",
        "    finalizedExpressions.push_back({&expression, category});",
        "    return TypedHookInput{solidity_Value_FinalizedExpressionLeaf, "
        "ordinal};",
        "  };",
        "  auto saveValueExpression =",
        "      [&](const ::neutrino::ExprNode &expression) -> TypedHookInput {",
        "    return saveExpression(expression, "
        "::neutrino::ExprCategory::Value);",
        "  };",
        "  auto savePredicateExpression =",
        "      [&](const ::neutrino::ExprNode &expression) -> TypedHookInput {",
        "    return saveExpression(expression, "
        "::neutrino::ExprCategory::Predicate);",
        "  };",
        "  switch (field) {",
    ]
    lines += project_lines
    lines += [
        "  default:",
        "    break;",
        "  }",
        "  return recipeError(RecipeDiagnostic::InputUnbound,",
        "                     \"Solidity projected field\");",
        "}",
        "",
        "// slotExtent(): map one slot to its finalized cardinality.",
        "inline ::llvm::Expected<unsigned> soliditySlotExtentResolve(",
        "    const ::neutrino::projection::FinalizedProjectionSequence &sequence,",
        "    SlotId slot, ::llvm::ArrayRef<SlotIndex> ctx) {",
        "  switch (slot) {",
    ]
    lines += extent_lines
    lines += [
        "  default:",
        "    break;",
        "  }",
        "  // The optional posting-presence slots resolve through the generated",
        "  // SlotRow presence + solidityOptionalSlotExtent (posting navigation).",
        "  if (const SlotRow *row = findSlot(solidityRecipeModule(), slot);",
        "      row != nullptr && row->presence != 0) {",
        "    if (row->parentSlot == solidity_Slot_groupPostings) {",
        "      const auto group = ::llvm::find_if(",
        "          ctx, [](const SlotIndex &item) {",
        "            return item.slot == solidity_Slot_effectGroups;",
        "          });",
        "      const auto posting = ::llvm::find_if(",
        "          ctx, [](const SlotIndex &item) {",
        "            return item.slot == solidity_Slot_groupPostings;",
        "          });",
        "      if (group == ctx.end() || posting == ctx.end() ||",
        "          group->index >= sequence.effectGroups.size() ||",
        "          posting->index >=",
        "              sequence.effectGroups[group->index]"
        ".finalizedPostings.size())",
        "        return recipeError(RecipeDiagnostic::InputUnbound,",
        "                           \"temporal group posting parent\");",
        "      return solidityOptionalSlotExtent(",
        "          row->presence, sequence.effectGroups[group->index]",
        "                             .finalizedPostings[posting->index]);",
        "    }",
        "    const SlotId parentSlot = row->parentSlot;",
        "    const auto parent = ::llvm::find_if(",
        "        ctx, [&](const SlotIndex &item) "
        "{ return item.slot == parentSlot; });",
        "    if (parent == ctx.end() || parent->index >= sequence.postings.size())",
        "      return recipeError(RecipeDiagnostic::InputUnbound,",
        "                         \"effectful posting parent\");",
        "    return solidityOptionalSlotExtent(row->presence,",
        "                                      sequence.postings[parent->index]);",
        "  }",
        "  return recipeError(RecipeDiagnostic::InputUnbound,",
        "                     \"Solidity finalized slot\");",
        "}",
        "",
        "// slotItemOrder(): map one repeated slot's item index to its ordinal.",
        "inline ::llvm::Expected<uint64_t> soliditySlotItemOrderResolve(",
        "    const ::neutrino::projection::FinalizedProjectionSequence &sequence,",
        "    SlotId slot, ::llvm::ArrayRef<SlotIndex> ctx, unsigned index) {",
        "  switch (slot) {",
    ]
    lines += order_lines
    lines += [
        "  default:",
        "    break;",
        "  }",
        "  return recipeError(RecipeDiagnostic::InputUnbound,",
        "                     \"Solidity finalized slot order\");",
        "}",
        "",
        "} // namespace generated_projection",
        "} // namespace solidity_model",
        "} // namespace neutrino",
        "",
    ]
    return "\n".join(lines)


