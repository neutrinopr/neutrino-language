def _fmt_arm_line(line, args):
    out = line
    if "{JOIN}" in out:
        out = out.replace("{JOIN}", ", ".join(cpp(a) for a in args))
    for i in range(len(args) - 1, -1, -1):
        out = out.replace("{A%d}" % i, cpp(args[i]))
        out = out.replace("{R%d}" % i, str(args[i]))
    return out


# ---------------------------------------------------------------------
# The normalized adapter IR + the ONE dispatch-arm engine shared by both
# homologous <backend>BuildNode adapters ( P1a). A normalized node
# carries its identity, ordered scalar operands, nested operands + takers,
# validated shape, and a backend emission action. The engine owns the
# duplicated traversal/branch/output machine (dispatcher shell, per-node
# guard framing, fallthrough, provenance); each backend supplies only a
# small arm-body callback for its emission action.
# ---------------------------------------------------------------------
class AdapterNode:
    __slots__ = ("name", "symbol", "values", "nested", "action", "leaves")

    def __init__(self, name, symbol, values, nested, action, leaves=None):
        self.name = name          # raw TargetNode identity (ordering key)
        self.symbol = symbol      # sanitized guard identity
        self.values = values      # [(operand_index, field_name)]
        self.nested = nested      # [(operand_index, field_name, taker)]
        self.action = action      # backend-specific emission payload
        self.leaves = leaves or []  # [(operand_index, field_name)] hook-escaped


def lower_adapter_nodes(data, classify, sort_key=None):
    """Shared traversal: every TargetNode whose `classify(row)` returns a node is
    normalized. `classify` returns an AdapterNode or None (skip); it also owns
    the backend's shape validation. Returns the deterministically ordered list."""
    nodes = []
    for name in data["!instanceof"]["TargetNode"]:
        node = classify(name, data[name])
        if node is not None:
            nodes.append(node)
    nodes.sort(key=sort_key if sort_key else (lambda n: n.name))
    return nodes


def classify_operands(data, row, takers, unknown_nested):
    """Shared field-order extraction: split a node's declared Fields into ordered
    scalar operands and nested operands (mapped to their taker)."""
    values, nested, leaves = [], [], []
    for idx, ref in enumerate(row.get("Fields", [])):
        field = data[record_name(ref)]
        field_name = field.get("Name")
        field_kind = field.get("Kind")
        if field_kind == "value":
            values.append((idx, field_name))
        elif field_kind == "leaf":
            # : a Hook<>-bound operand (e.g. the string.escape-escaped
            # ledger/proc/entry/memo), read from the produced-leaf pool.
            leaves.append((idx, field_name))
        elif field_kind == "nodes":
            taker = takers.get(field_name)
            if taker is None:
                raise SystemExit(unknown_nested(field_name))
            nested.append((idx, field_name, taker))
    return values, nested, leaves


def emit_operand_binds(node):
    """Shared arm prologue: bind each scalar/leaf operand and take each nested
    child, fail-closed. Both dispatchers consume the same normalized lists."""
    out = []
    for idx, fname in node.values:
        out += [
            f"    auto {fname} = adapter.valueOperand("
            f"session, bindings, fields, {idx}u);",
            f"    if (!{fname})",
            f"      return {fname}.takeError();",
        ]
    for idx, fname in node.leaves:
        out += [
            f"    auto {fname} = adapter.leafOperand("
            f"session, bindings, fields, {idx}u);",
            f"    if (!{fname})",
            f"      return {fname}.takeError();",
        ]
    for idx, fname, taker in node.nested:
        out += [
            f"    auto {fname} = adapter.{taker}("
            f"session, bindings, fields, {idx}u);",
            f"    if (!{fname})",
            f"      return {fname}.takeError();",
        ]
    return out


def emit_adapter_dispatcher(generated_by, fn_name, backend_desc, node_prefix,
                            nodes, arm_body, source_digest):
    """The one dispatch-arm engine: the shared dispatcher shell, per-node guard
    framing, and fallthrough. `arm_body(node)` yields the backend's emission for
    one node (between the guard braces)."""
    lines = [
        f"// GENERATED by {generated_by} -- DO NOT EDIT.",
        f"// Source-SHA256: {source_digest}",
        "namespace neutrino { namespace recipe { namespace generated {",
        "template <typename Adapter>",
        "inline llvm::Expected<TargetNodeRef>",
        f"{fn_name}(Adapter &adapter, OpaqueBuildSession &session,",
        "                  BackendNodeTypeId node,",
        "                  llvm::ArrayRef<GeneratedFieldBinding> bindings,",
        "                  llvm::ArrayRef<TargetFieldDescriptor> fields) {",
    ]
    for node in nodes:
        lines.append(f"  if (node == {node_prefix}{node.symbol}) {{")
        lines += arm_body(node)
        lines.append("  }")
    lines += [
        "  return recipeError(RecipeDiagnostic::OperationForbidden,",
        f'                     "unknown generated {backend_desc} target node");',
        "}",
        "} } } // namespace neutrino::recipe::generated",
        "",
    ]
    return "\n".join(lines)


def postgres_recipe_adapter_generate(td, includes, tblgen):
    data = load_records(td, includes, tblgen)

    def classify(name, row):
        kind = row.get("BuilderKind", "")
        if not kind:
            return None
        spec = PG_ADAPTER_ARMS.get(kind)
        if spec is None:
            raise SystemExit(f"{name}: unknown PostgreSQL builder kind {kind!r}")
        args = list(row.get("BuilderArgs", []))
        values, nested, leaves = classify_operands(
            data, row, PG_ADAPTER_TAKERS,
            lambda fn: f"{name}: unknown nested field {fn!r}")
        # : shape is (value, nested, args[, leaf]); a 3-tuple pins leaf = 0.
        shape = spec["shape"]
        nleaf = shape[3] if len(shape) > 3 else 0
        if (len(values), len(nested), len(args), len(leaves)) != (
                shape[0], shape[1], shape[2], nleaf):
            raise SystemExit(
                f"{name}: invalid {kind!r} descriptor "
                f"(values={len(values)}, nested={len(nested)}, "
                f"args={len(args)}, leaves={len(leaves)})")
        identity = row.get("Name")
        return AdapterNode(identity, identity, values, nested, (kind, args),
                           leaves)

    nodes = lower_adapter_nodes(data, classify)
    if not nodes:
        raise SystemExit("no PostgreSQL recipe builder nodes found")

    def arm_body(node):
        kind, args = node.action
        return emit_operand_binds(node) + [
            _fmt_arm_line(line, args) for line in PG_ADAPTER_ARMS[kind]["emit"]]

    source_digest = profile_source_sha256(
        [postgres_recipe_adapter_generate, _fmt_arm_line,
         PG_ADAPTER_ARMS, PG_ADAPTER_TAKERS],
        [td])
    return emit_adapter_dispatcher(
        "scripts/generators/backend_recipe_gen.py --profile "
        "postgres-recipe-adapter", "postgresBuildNode",
        "PostgreSQL", "postgres_Node_", nodes, arm_body, source_digest)


def _run_postgres_recipe_adapter(argv):
    parser = argparse.ArgumentParser()
    parser.add_argument("--td", required=True)
    parser.add_argument("--tblgen", required=True)
    parser.add_argument("-I", action="append", default=[])
    parser.add_argument("-o", required=True)
    args = parser.parse_args(argv)
    with open(args.o, "w", encoding="utf-8") as output:
        output.write(postgres_recipe_adapter_generate(args.td, args.I, args.tblgen))
    return 0


