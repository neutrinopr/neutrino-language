def _fresh_pg_ddl_symbols():
    """The  slice-2 raw-DDL carrier construction spellings
    (pgddl::DdlCap::forge / rawSql / operator+), authenticated by regenerating
    PgDdlBuilders.inc byte-for-byte from the closed PostgresDdlCarrier.td
    descriptor + generator (). Construction is mechanically emitted there;
    a handwritten copy outside this artifact is not authenticated (its source
    path is not PG_DDL_ARTIFACT), so the census still flags it as a candidate."""
    global _PG_DDL_SYMBOLS_CACHE
    if _PG_DDL_SYMBOLS_CACHE is not None:
        return _PG_DDL_SYMBOLS_CACHE
    artifact = _read(PG_DDL_ARTIFACT)
    if artifact != _regenerated_pg_ddl_artifact():
        raise CensusError(
            "PostgreSQL raw-DDL carrier artifact differs from regenerated bytes")
    # Each name is a top-level definition in the byte-verified generated
    # artifact (the freshness check binds these bytes to the generator). Match
    # the RawSql/DdlCap-returning minter, combiner, and capability mint.
    symbols = set(re.findall(
        r"(?:RawSql|DdlCap)\s+(?:DdlCap::)?(operator\+|[A-Za-z_][A-Za-z0-9_]*)"
        r"\s*\(",
        artifact))
    if not symbols:
        raise CensusError(
            "fresh PostgreSQL raw-DDL carrier artifact exports no construction")
    _PG_DDL_SYMBOLS_CACHE = symbols
    return symbols


def _fresh_generated_projection_symbols():
    """Authenticate the generated finalized-view projection resolvers ( R5b)
    for both backends: regenerate each *Projection.inc byte-for-byte from its
    projection schema .td + generator, and require the named provider to consume
    the committed artifact. Returns {provider basename -> {resolver symbols}}.

    Only fresh, registered resolvers are recognized as generated dispatch; a
    handwritten definition that does not byte-match the regenerated artifact is
    absent from this set and stays counted as a declarative-recipe-candidate."""
    global _PROJECTION_SYMBOLS_CACHE
    if _PROJECTION_SYMBOLS_CACHE is not None:
        return _PROJECTION_SYMBOLS_CACHE
    result = {}
    for spec in PROJECTION_ARTIFACTS:
        artifact = _read(spec["artifact"])
        if artifact != _regenerated_projection_artifact(
                spec["profile"], spec["td"], spec["extra"]):
            raise CensusError(
                f"{os.path.basename(spec['artifact'])} differs from "
                "regenerated bytes")
        symbols = set(re.findall(
            r"\ninline ::llvm::Expected<[^\n]+>\s+"
            r"([A-Za-z_][A-Za-z0-9_]*)\(", artifact))
        if not symbols:
            raise CensusError(
                f"fresh {os.path.basename(spec['artifact'])} exports no "
                "projection resolver")
        include = f'#include "{os.path.basename(spec["artifact"])}"'
        if include not in _read(spec["provider"]):
            raise CensusError(
                f"{os.path.basename(spec['provider'])} does not consume the "
                f"authenticated {os.path.basename(spec['artifact'])}")
        result[os.path.basename(spec["provider"])] = symbols
    _PROJECTION_SYMBOLS_CACHE = result
    return result


