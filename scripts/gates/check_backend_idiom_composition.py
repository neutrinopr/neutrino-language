def _fresh_pg_builder_symbols():
    """Builder spellings authenticated by regenerating the PostgreSQL builder
    artifact byte-for-byte (the  shape/builder bootstrap has no recipe
    provider/module yet, so there is no package/provider consumption to bind)."""
    global _PG_BUILDER_SYMBOLS_CACHE
    if _PG_BUILDER_SYMBOLS_CACHE is not None:
        return _PG_BUILDER_SYMBOLS_CACHE
    artifact = _read(PG_BUILDER_ARTIFACT)
    if artifact != _regenerated_pg_builder_artifact():
        raise CensusError(
            "PostgreSQL recipe-builder artifact differs from regenerated bytes")
    # Provenance-anchored: every name is a top-level definition in the
    # byte-verified generated artifact (the freshness check above binds these
    # bytes to the generator), so this keys on generated provenance, not code
    # shape in a handwritten file.  restructured the surface into the
    # `std::optional<PgStmt>` emit builders, the `PgStmt PgStmt::<factory>` node
    # constructors, and the `codetext::Node renderPgStmtTree` typed-tree
    # renderer — match each definition's leaf name.
    symbols = set(re.findall(
        r"(?:std::optional<PgStmt>|\bPgStmt|codetext::Node)\s+"
        r"(?:PgStmt::)?([A-Za-z_][A-Za-z0-9_]*)\s*\(",
        artifact))
    if not symbols:
        raise CensusError(
            "fresh PostgreSQL recipe-builder artifact exports no builder")
    _PG_BUILDER_SYMBOLS_CACHE = symbols
    return symbols


