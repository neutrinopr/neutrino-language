# The ratchet identity is a STABLE STRUCTURAL SLOT, not the exact source bytes
# ( architect ruling): (target, file, symbolUsr, astKind, occurrenceKind,
# ownerIssue, ownershipSlice, ordinal-within-that-group). Owner/slice are part of
# the identity so an owner-only reassignment cannot escape (classification is
# already selected by the caller). Editing an existing occurrence's body keeps
# its slot — `tokenSha256` still records the exact bytes as audit evidence — while
# ADDING a sibling, MOVING an occurrence across symbols/files/owners, an
# owner-only reassignment, or a handwritten copy of generated construction lands
# in a NEW slot and is caught as growth.
def _slot_counts(rows):
    groups = {}
    for row in rows:
        file_name = row["file"]
        symbol_usr = row["symbolUsr"]
        migrated = _SOURCE_SPLIT_SLOT_MIGRATIONS.get(
            (row["target"], file_name, row["symbol"]))
        if migrated is not None:
            file_name, symbol_usr = migrated
        base = (row["target"], file_name, symbol_usr,
                row["astKind"], row["occurrenceKind"],
                row.get("ownerIssue"), row.get("ownershipSlice"))
        groups[base] = groups.get(base, 0) + 1
    counts = {}
    for base, multiplicity in groups.items():
        for ordinal in range(multiplicity):
            counts[base + (ordinal,)] = 1
    return counts


def _candidate_counter(report):
    return _slot_counts([
        row for row in report["occurrences"]
        if row["classification"] == "declarative-recipe-candidate"])


def _exclusion_counter(report):
    return _slot_counts(report["authenticatedExclusions"])


def _validate_nonincrease(report, base):
    if base is None:
        return
    for label, counter in (
            ("handwritten recipe-candidate", _candidate_counter),
            ("authenticated exclusion", _exclusion_counter)):
        current = counter(report)
        previous = counter(base)
        growth = [
            (key, count, previous.get(key, 0))
            for key, count in current.items()
            if count > previous.get(key, 0)
        ]
        if growth:
            key, count, old_count = sorted(growth)[0]
            raise CensusError(
                f"{label} growth is forbidden: "
                f"{key} increased {old_count}->{count}")


def _require_complete(report):
    if report["completion"]["verdict"] != "complete":
        raise CensusError(
            "census is not complete: "
            + json.dumps(report["completion"], sort_keys=True))


def _load_base_report(base_ref, output_rel):
    if not base_ref:
        return None
    resolved = subprocess.run(
        ["git", "rev-parse", "--verify", f"{base_ref}^{{commit}}"],
        cwd=REPO, text=True, stdout=subprocess.PIPE,
        stderr=subprocess.PIPE)
    if resolved.returncode:
        raise CensusError(f"cannot resolve census base ref {base_ref}")
    proc = subprocess.run(
        ["git", "show", f"{base_ref}:{output_rel}"],
        cwd=REPO, text=True, stdout=subprocess.PIPE,
        stderr=subprocess.PIPE)
    if proc.returncode:
        # The S0 census PR is the one permitted baseline creation. Once the
        # artifact exists on the base, every later generation is ratcheted.
        return None
    try:
        return json.loads(proc.stdout)
    except ValueError as exc:
        raise CensusError(f"base census is malformed: {exc}")


