def _classify(backend, rel, event, security):
    if event.get("_carveoutId"):
        return ("security-carveout-656", 656, "security-carveout-656",
                event["_carveoutId"],
                "AST reference to an exact-body  registry artifact")
    for sec_rel, begin, end, entry_id in security:
        if rel == sec_rel and begin <= event["offset"] < end:
            return ("security-carveout-656", 656, "security-carveout-656",
                    entry_id,
                    "exact reviewed-generator region")
    if event["symbol"] in EXCLUDED_PRINTER_SYMBOLS:
        return None
    if event["symbol"] in REGISTERED_LEAF_HOOKS:
        issue, hook_id = REGISTERED_LEAF_HOOKS[event["symbol"]]
        return (
            "pure-leaf-hook", issue, f"registered-leaf-hook-{hook_id}",
            None, "exact symbol in the generated registered leaf-hook ABI",
        )
    if event["symbol"] in GENERIC_DRIVER_SYMBOLS:
        driver_id = GENERIC_DRIVER_SYMBOLS[event["symbol"]]
        return (
            "generic-driver-validation", 898,
            f"generic-driver-{driver_id}-issue-898",
            None,
            "exact registered traversal over an already-composed typed target "
            "tree; it cannot select a target, recipe, or semantic behavior",
        )
    generated_builders = _fresh_generated_builder_symbols()
    generated_emit_builders = _fresh_generated_emit_builder_symbols()
    if rel in {SOLIDITY_EMIT_BUILDER_DECLS, SOLIDITY_EMIT_BUILDERS} and \
            event["symbol"].rsplit("::", 1)[-1] in generated_emit_builders:
        return (
            "generated-provider-construction", 900,
            "fresh-package-generated-emit-builder", None,
            "AST spelling originates in the package-owned generated Emit "
            "artifact whose full bytes bind its target-node registry and "
            "generator inputs",
        )
    if rel == SOLIDITY_BUILDER_ARTIFACT and \
            event["symbol"].rsplit("::", 1)[-1] in generated_builders:
        return (
            "generated-provider-construction", 900,
            "fresh-package-generated-builder", None,
            "AST spelling originates in the package-owned generated artifact "
            "whose digest binds its TableGen and generator inputs",
        )
    if rel == PG_BUILDER_ARTIFACT and \
            event["symbol"].rsplit("::", 1)[-1] in _fresh_pg_builder_symbols():
        return (
            "generated-provider-construction", 904,
            "fresh-generated-builder", None,
            "AST spelling originates in the  generated recipe-builder "
            "artifact whose digest binds its TableGen and generator inputs",
        )
    if rel == PG_ADAPTER_ARTIFACT and \
            event["symbol"].rsplit("::", 1)[-1] in _fresh_pg_adapter_symbols():
        return (
            "generated-provider-construction", 905,
            "fresh-generated-recipe-adapter", None,
            "AST spelling originates in the  generated recipe adapter whose "
            "digest binds its recipe .td and generator inputs",
        )
    if rel == PG_DDL_ARTIFACT and \
            event["symbol"].rsplit("::", 1)[-1] in _fresh_pg_ddl_symbols():
        return (
            "generated-provider-construction", 680,
            "fresh-generated-ddl-carrier", None,
            "AST spelling originates in the  generated raw-DDL carrier "
            "construction whose digest binds its closed descriptor and "
            "generator inputs",
        )
    # : the package-local  security resolvers (PostgresModel.cpp is the
    # PG-QUORUM-SINGLE(+REVOKE) allowed consumer) forward the exact reviewed
    # gate/revoke generator into the recipe's declarative order — plumbing, not a
    # recipe candidate or a handwritten composition.
    if event["symbol"] in PG_SECURITY_RESOLVERS:
        return (
            "provider-plumbing", 905,
            "pg-656-security-resolver", None,
            "package-local  security resolver forwarding the exact reviewed "
            "gate/revoke generator into the recipe's declarative order",
        )
    if event["symbol"] in PG_RENDER_PLUMBING:
        return (
            "provider-plumbing", 904,
            "pg-common-render-printer", None,
            " common-render printer adapter rendering already-composed typed "
            "statements to SQL text; not rail-specific and not a leaf hook",
        )
    role = _registered_source_role(rel)
    if role == "recipe-provider-plumbing":
        owner = 905 if rel.startswith("lib/backends/postgres/") else 900
        if event.get("callee") in generated_builders:
            return (
                "generated-provider-construction", owner,
                "fresh-package-generated-builder", None,
                "callee spelling is exported by the package-owned generated "
                "artifact whose digest binds its TableGen and generator "
                "inputs",
            )
        if event.get("callee") in {
                "docComment", "interfaceSignature", "interfaceShell"}:
            return (
                "forbidden-residue", 897,
                "handwritten-provider-construction", None,
                "concrete target-node factories must spell from the fresh "
                "generated builder artifact",
            )
        return (
            "provider-plumbing", owner,
            "cmake-registered-recipe-provider-plumbing", None,
            "CMake-registered provider storage/recheck/render plumbing; "
            "concrete construction is freshness-bound generated output",
        )
    issue = CANDIDATE_SYMBOL_ISSUES.get(event["symbol"])
    if issue is None:
        return (
            "forbidden-residue", 897, "forbidden-unassigned-symbol",
            None,
            "governed target-node composition symbol has no reviewed bounded "
            "candidate, hook, generic, or  registration",
        )
    target, family = next(
        key for key, value in SLICE_ISSUES.items() if value == issue)
    if target != backend:
        return (
            "forbidden-residue", 897, "forbidden-cross-target-owner",
            None,
            "candidate symbol is registered to a different backend target",
        )
    return (
        "declarative-recipe-candidate",
        issue,
        f"{backend}-{family}-issue-{issue}",
        None,
        "backend-specific handwritten target-node composition assigned to "
        f"the bounded {backend} {family} extraction slice #{issue}",
    )


def _completion(rows):
    unassigned = sum(row["ownerIssue"] is None for row in rows)
    umbrella = sum(
        row["classification"] == "declarative-recipe-candidate"
        and row["ownerIssue"] in (661, 897, 898)
        for row in rows)
    backend_generic = sum(
        row["classification"] == "generic-driver-validation"
        and row["symbol"] not in GENERIC_DRIVER_SYMBOLS
        for row in rows)
    forbidden = sum(
        row["classification"] == "forbidden-residue" for row in rows)
    return {
        "unassignedOwnerOccurrences": unassigned,
        "umbrellaCandidateOccurrences": umbrella,
        "backendSpecificGenericOccurrences": backend_generic,
        "forbiddenResidueOccurrences": forbidden,
        "verdict": (
            "complete"
            if unassigned == 0 and umbrella == 0
            and backend_generic == 0 and forbidden == 0
            else "blocked-pending-owner-partition"
        ),
    }


