def _validate(report):
    required = {
        "kind", "schemaVersion", "sourceRevision", "schema", "discovery",
        "securityRegistry", "totals", "ownershipSlices", "symbolSummary",
        "authenticatedExclusions", "sourceDispositions", "completion",
        "occurrences",
    }
    if set(report) != required:
        raise CensusError("census top-level shape drift")
    if report["kind"] != "neutrino.backend-idiom-composition-inventory" \
            or report["schemaVersion"] != 1:
        raise CensusError("census identity drift")
    if (len(report["securityRegistry"]["entryIds"]) != 7
            or report["securityRegistry"]["resolverRows"] != 5):
        raise CensusError(" registry denominator drift")
    allowed = {
        "declarative-recipe-candidate", "pure-leaf-hook",
        "security-carveout-656", "generic-driver-validation",
        "generated-provider-construction", "generated-provider-invocation",
        "provider-plumbing", "forbidden-residue",
    }
    ids = set()
    seen_carveouts = set()
    admitted_carveouts = set(report["securityRegistry"]["entryIds"])
    # Every generated-provider-construction row must trace to a builder artifact
    # whose committed bytes regenerate byte-for-byte; the same provenance
    # machinery, keyed per artifact by its owning slice (Solidity , the
    # PostgreSQL shape/builder bootstrap). No parallel mechanism.
    builder_artifacts = {
        SOLIDITY_BUILDER_ARTIFACT: (900, _fresh_generated_builder_symbols),
        PG_BUILDER_ARTIFACT: (904, _fresh_pg_builder_symbols),
        PG_ADAPTER_ARTIFACT: (905, _fresh_pg_adapter_symbols),
        PG_DDL_ARTIFACT: (680, _fresh_pg_ddl_symbols),
    }
    for row in report["occurrences"]:
        if row["id"] in ids or row["classification"] not in allowed:
            raise CensusError("duplicate or unclassified census row")
        ids.add(row["id"])
        if row["ownerIssue"] is None:
            raise CensusError(f"{row['id']}: ownerIssue is mandatory")
        if (row["classification"] == "declarative-recipe-candidate"
                and row["ownerIssue"] not in set(SLICE_ISSUES.values())):
            raise CensusError(
                f"{row['id']}: candidate lacks bounded extraction issue")
        if row["classification"] == "security-carveout-656" \
                and row["ownerIssue"] != 656:
            raise CensusError(f"{row['id']}:  row has wrong owner")
        if row["classification"] == "generic-driver-validation" \
                and row["ownerIssue"] != 898:
            raise CensusError(f"{row['id']}: generic substrate has wrong owner")
        if row["classification"] == "generated-provider-construction":
            spec = builder_artifacts.get(row["file"])
            artifact_spelling = (
                spec is not None
                and row["ownerIssue"] == spec[0]
                and row["symbol"].rsplit("::", 1)[-1] in spec[1]())
            emit_artifact_spelling = (
                row["file"] in {
                    SOLIDITY_EMIT_BUILDER_DECLS,
                    SOLIDITY_EMIT_BUILDERS,
                }
                and row["ownerIssue"] == 900
                and row["symbol"].rsplit("::", 1)[-1]
                in _fresh_generated_emit_builder_symbols())
            # Provider forwarding (callee spelling) is the Solidity path only;
            # the  bootstrap has no provider yet (deferred to ).
            provider_invocation = (
                row["ownerIssue"] == 900
                and row.get("callee") in _fresh_generated_builder_symbols())
            if not (
                    artifact_spelling or emit_artifact_spelling
                    or provider_invocation):
                raise CensusError(
                    f"{row['id']}: generated builder lacks exact provenance")
        if row["classification"] == "provider-plumbing":
            # The   security resolvers and the  common-render printer
            # adapters are package-local plumbing in their allowed-consumer TUs
            # (not CMake-roled provider files), each pinned by an exact reviewed
            # symbol registry; every other provider-plumbing row must carry the
            # recipe-provider-plumbing CMake role (Solidity  / PostgreSQL
            # ).
            is_resolver = (row["symbol"] in PG_SECURITY_RESOLVERS
                           and row["ownerIssue"] == 905)
            is_render = (row["symbol"] in PG_RENDER_PLUMBING
                         and row["ownerIssue"] == 904)
            roled = (row["ownerIssue"] in (900, 905) and
                     _registered_source_role(row["file"]) ==
                     "recipe-provider-plumbing")
            if not (is_resolver or is_render or roled):
                raise CensusError(
                    f"{row['id']}: provider plumbing lacks CMake role")
        if row["classification"] == "generated-provider-invocation":
            authorized = AUTHORIZED_RECIPE_CALLS.get(
                (row["symbol"], row.get("callee")))
            if authorized is None or \
                    row.get("recipeKey") != authorized[0] or \
                    row.get("ownerIssue") != authorized[1]:
                raise CensusError(
                    f"{row['id']}: provider invocation lacks exact provenance")
        if row["classification"] == "security-carveout-656" \
                and not row["carveoutId"]:
            raise CensusError(f"{row['id']}: security row lacks  identity")
        if row["classification"] == "security-carveout-656":
            if row["carveoutId"] not in admitted_carveouts:
                raise CensusError(
                    f"{row['id']}: unknown  identity {row['carveoutId']}")
            seen_carveouts.add(row["carveoutId"])
    if seen_carveouts != admitted_carveouts:
        raise CensusError(
            " occurrence coverage does not match the seven-entry registry")
    expected_recipe_calls = {
        (symbol, callee, key)
        for (symbol, callee), (key, _) in AUTHORIZED_RECIPE_CALLS.items()
    }
    actual_recipe_calls = {
        (row["symbol"], row.get("callee"), row.get("recipeKey"))
        for row in report["occurrences"] if row.get("recipeKey") is not None
    }
    has_authorized_surface = any(
        any(row["symbol"] == symbol
            for symbol, _ in AUTHORIZED_RECIPE_CALLS)
        for row in report["occurrences"])
    if (has_authorized_surface and
            actual_recipe_calls != expected_recipe_calls) or (
            not has_authorized_surface and actual_recipe_calls):
        raise CensusError(
            "authorized exact-key caller substitution provenance drift")
    counts = {}
    for row in report["occurrences"]:
        counts[row["classification"]] = counts.get(row["classification"], 0) + 1
    if report["totals"] != {
            "occurrences": len(report["occurrences"]),
            "byClassification": dict(sorted(counts.items()))}:
        raise CensusError("census totals do not reconcile")
    expected_summary = {}
    for row in report["occurrences"]:
        key = (
            row["target"], row["symbol"], row["symbolUsr"],
            row["classification"], row["ownerIssue"], row["ownershipSlice"],
        )
        expected_summary[key] = expected_summary.get(key, 0) + 1
    actual_summary = {
        (
            row["target"], row["symbol"], row["symbolUsr"],
            row["classification"], row["ownerIssue"], row["ownershipSlice"],
        ): row["occurrences"]
        for row in report["symbolSummary"]
    }
    if actual_summary != expected_summary \
            or len(actual_summary) != len(report["symbolSummary"]):
        raise CensusError("classification-by-symbol summary drift")
    expected_slices = {}
    for row in report["occurrences"]:
        if row["classification"] != "declarative-recipe-candidate":
            continue
        key = (row["ownerIssue"], row["ownershipSlice"], row["target"])
        group = expected_slices.setdefault(key, {"count": 0, "symbols": set()})
        group["count"] += 1
        group["symbols"].add(row["symbol"])
    actual_slices = {
        (row["ownerIssue"], row["id"], row["target"]): {
            "count": row["occurrences"],
            "symbols": set(row["symbols"]),
        }
        for row in report["ownershipSlices"]
    }
    if actual_slices != expected_slices \
            or len(actual_slices) != len(report["ownershipSlices"]):
        raise CensusError("bounded ownership-slice summary drift")
    if report["completion"] != _completion(report["occurrences"]):
        raise CensusError("census completion state does not reconcile")
    exclusion_ids = set()
    for row in report["authenticatedExclusions"]:
        if row["id"] in exclusion_ids:
            raise CensusError("duplicate authenticated exclusion identity")
        exclusion_ids.add(row["id"])
        if row["symbol"] not in EXCLUDED_PRINTER_SYMBOLS:
            raise CensusError(
                f"{row['id']}: exclusion lacks exact authenticated symbol")
    expected_dispositions = {
        (backend, rel)
        for backend, source in report["discovery"]["sources"].items()
        for rel in source["files"]
    }
    actual_dispositions = {
        (row["target"], row["file"]) for row in report["sourceDispositions"]
    }
    if actual_dispositions != expected_dispositions \
            or len(actual_dispositions) != len(report["sourceDispositions"]):
        raise CensusError("source-disposition denominator drift")
    for row in report["sourceDispositions"]:
        governed = sum(
            occurrence["target"] == row["target"]
            and occurrence["file"] == row["file"]
            for occurrence in report["occurrences"])
        excluded = sum(
            occurrence["target"] == row["target"]
            and occurrence["file"] == row["file"]
            for occurrence in report["authenticatedExclusions"])
        if governed != row["governedOccurrences"] \
                or excluded != row["authenticatedExclusions"]:
            raise CensusError(
                f"{row['file']}: source disposition count drift")
        expected = (
            "covered" if governed or excluded
            else (
                "authenticated-leaf-formatting-only"
                if row["file"] in LEAF_FORMAT_ONLY_SOURCES
                else "authenticated-no-governed-ast-occurrence"
            ))
        if row["disposition"] != expected:
            raise CensusError(
                f"{row['file']}: dishonest source disposition")


def _projection_provenance_selftest():
    """Bite the  R5b resolver-provenance binding directly against _function_nodes.

    A registered projection resolver is exempted (not a census row) ONLY when its
    true document-order origin file is the exact *Projection.inc registered for the
    provider. The same resolver spelling reached from any other file — handwritten
    in the provider body, or from an unrelated included header — has a different
    origin and stays governed. Builds the two clang-AST shapes (loc.file present on
    the include-boundary node; inherited/None on the resolver) and asserts each
    outcome, so a regression that widened the check back to `includedFrom`-non-null
    (which every include satisfies) fails here."""
    provider_rel = PROJECTION_ARTIFACTS[1]["provider"]  # PostgresRecipeProvider.cpp
    provider_abs = os.path.join(REPO, provider_rel)
    base_name = os.path.basename(provider_rel)
    artifact_abs = _projection_artifact_abspath(base_name)
    resolvers = _fresh_generated_projection_symbols()[base_name]
    resolver = sorted(resolvers)[0]
    other_inc = os.path.join(
        REPO, "lib/backends/postgres/generated/PostgresRecipeAdapter.inc")

    src = b"inline int " + resolver.encode() + b"(){ return 0; }"
    usr_rows = [(1, "c:@F@" + resolver + "#")]

    def _tree(origin_file):
        # A TranslationUnitDecl attributed to the provider (children inherit the
        # provider as current_file), a boundary FunctionDecl that stamps the running
        # origin to `origin_file` (no body -> never itself a row), then the resolver
        # with an inherited location (loc.file absent) — exactly clang's shape for a
        # fragment included from a generated .inc.
        return {
            "kind": "TranslationUnitDecl",
            "loc": {"file": provider_abs},
            "inner": [
                {"kind": "FunctionDecl", "name": "__origin_boundary__",
                 "loc": {"file": origin_file},
                 "range": {"begin": {"offset": 0}, "end": {"offset": 0}},
                 "inner": []},
                {"kind": "FunctionDecl", "name": resolver,
                 # `includedFrom` present on all three shapes (the exact clang tell
                 # that a node came from *some* include). The ONLY thing that varies
                 # across the cases is the running origin file — so a regression that
                 # keyed off `includedFrom` alone would wrongly exempt all three.
                 "loc": {"includedFrom": {"file": provider_abs}},
                 "range": {"begin": {"offset": 0},
                           "end": {"offset": len(src) - 1, "tokLen": 1}},
                 "inner": [{"kind": "CompoundStmt",
                            "range": {"begin": {"offset": src.index(b"{")},
                                      "end": {"offset": len(src) - 1,
                                              "tokLen": 1}},
                            "inner": []}]},
            ],
        }

    def _rows(origin_file):
        return _function_nodes([_tree(origin_file)], provider_abs, src, usr_rows)

    if _rows(artifact_abs):
        raise CensusError(
            "projection resolver from its registered artifact was NOT exempted")
    if not _rows(provider_abs):
        raise CensusError(
            "a resolver-named function handwritten in the provider was wrongly "
            "exempted (provenance binding is vacuous)")
    if not _rows(other_inc):
        raise CensusError(
            "a resolver-named function from an unrelated include was wrongly "
            "exempted (provenance binding is not artifact-exact)")


