def main():
    parser = argparse.ArgumentParser()
    parser.add_argument(
        "--build-dir",
        default=os.environ.get("NEUTRINO_BUILD_DIR", os.path.join(REPO, "out")),
    )
    parser.add_argument("--output", default=DEFAULT_OUTPUT)
    parser.add_argument("--base-ref", default="origin/main")
    parser.add_argument("--write", action="store_true")
    parser.add_argument("--selftest", action="store_true")
    args = parser.parse_args()
    global BUILD_DIR
    BUILD_DIR = args.build_dir
    try:
        if args.selftest:
            selftest()
            return 0
        report = generate(os.path.abspath(args.build_dir))
        _validate(report)
        _require_complete(report)
        output_rel = os.path.relpath(
            os.path.join(REPO, args.output)
            if not os.path.isabs(args.output) else args.output,
            REPO).replace(os.sep, "/")
        _validate_nonincrease(
            report, _load_base_report(args.base_ref, output_rel))
        payload = json.dumps(report, indent=2, sort_keys=True) + "\n"
        output = os.path.join(REPO, args.output)
        if args.write:
            os.makedirs(os.path.dirname(output), exist_ok=True)
            with open(output, "w", encoding="utf-8") as f:
                f.write(payload)
            print(f"wrote {args.output}: {len(report['occurrences'])} rows")
            return 0
        try:
            committed = open(output, encoding="utf-8").read()
        except OSError as exc:
            raise CensusError(f"committed census missing: {exc}")
        if committed != payload:
            raise CensusError(
                "committed census is stale; regenerate with --write")
        print(
            f"backend-idiom-composition: PASS "
            f"({len(report['occurrences'])} occurrences)")
        return 0
    except (CensusError, OSError, ValueError, subprocess.CalledProcessError) as exc:
        print(f"backend-idiom-composition: {exc}", file=sys.stderr)
        return 1


if __name__ == "__main__":
    sys.exit(main())
