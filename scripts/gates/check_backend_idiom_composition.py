BUILD_DIR = ""


def _abspath(rel):
    if generated_artifacts.is_migrated(rel):
        return generated_artifacts.resolve(rel, BUILD_DIR)
    return os.path.join(REPO, rel)


def _read(rel):
    with open(_abspath(rel), encoding="utf-8", errors="replace") as f:
        return f.read()


def _read_bytes(rel):
    with open(_abspath(rel), "rb") as f:
        return f.read()


def _json_stream(payload):
    decoder = json.JSONDecoder()
    offset = 0
    while offset < len(payload):
        while offset < len(payload) and payload[offset].isspace():
            offset += 1
        if offset == len(payload):
            return
        item, offset = decoder.raw_decode(payload, offset)
        yield item


def _compiled_backend_translation_units(compdb, root_rel):
    root = os.path.realpath(os.path.join(REPO, root_rel))
    found = []
    for row in compdb:
        raw = row.get("file")
        if not raw:
            continue
        path = raw if os.path.isabs(raw) else os.path.join(
            row.get("directory") or REPO, raw)
        path = os.path.realpath(path)
        if os.path.commonpath((root, path)) != root:
            continue
        rel = os.path.relpath(path, REPO).replace(os.sep, "/")
        if "/test/" in "/" + rel or not rel.endswith(
                (".cpp", ".cc", ".cxx")):
            continue
        found.append(rel)
    return sorted(set(found))


def _discover_sources(compdb):
    found = {}
    for backend, spec in BACKENDS.items():
        root = os.path.join(REPO, spec["root"])
        files_found = []
        translation_units = _compiled_backend_translation_units(
            compdb, spec["root"])
        for directory, subdirs, files in os.walk(root):
            subdirs[:] = [d for d in subdirs if d != "test"]
            for name in files:
                if not name.endswith((".cpp", ".cc", ".cxx",
                                      ".h", ".hh", ".hpp", ".inc")):
                    continue
                path = os.path.join(directory, name)
                rel = os.path.relpath(path, REPO).replace(os.sep, "/")
                files_found.append(rel)
        # Generated fragments remain part of the governed backend surface even
        # though they are no longer present in the source walk. Add their
        # canonical identities mechanically; _abspath resolves their bytes from
        # the configured build tree and refuses missing/truncated products.
        prefix = spec["root"].rstrip("/") + "/"
        files_found.extend(
            rel for rel in generated_artifacts.MIGRATED_ARTIFACTS
            if rel.startswith(prefix)
        )
        if not files_found or not translation_units:
            raise CensusError(f"{backend}: AST source discovery is empty")
        missing_from_tree = sorted(set(translation_units) - set(files_found))
        if missing_from_tree:
            raise CensusError(
                f"{backend}: compiled production sources absent from backend "
                f"tree discovery: {missing_from_tree}")
        found[backend] = {
            "files": sorted(set(files_found)),
            "translationUnits": translation_units,
            "translationUnitAuthority": "compile_commands.json",
        }
    return found


def _load_compdb(build_dir):
    path = os.path.join(build_dir, "compile_commands.json")
    try:
        with open(path, encoding="utf-8") as f:
            rows = json.load(f)
    except (OSError, ValueError) as exc:
        raise CensusError(f"cannot read compilation database {path}: {exc}")
    if not isinstance(rows, list) or not rows:
        raise CensusError("compilation database is empty")
    return rows


_COMPATIBLE_ISYSROOT = "unset"


def _isysroot_of(command):
    for index, arg in enumerate(command):
        if arg == "-isysroot" and index + 1 < len(command):
            return command[index + 1]
        if arg.startswith("-isysroot") and arg != "-isysroot":
            return arg[len("-isysroot"):]
        if arg.startswith("--sysroot="):
            return arg[len("--sysroot="):]
    return None


def _with_isysroot(command, sdk):
    out, skip, replaced = [], False, False
    for arg in command:
        if skip:
            skip = False
            continue
        if arg == "-isysroot":
            out += ["-isysroot", sdk]
            skip = True
            replaced = True
        elif arg.startswith("-isysroot") and arg != "-isysroot":
            out.append("-isysroot" + sdk)
            replaced = True
        elif arg.startswith("--sysroot="):
            out.append("--sysroot=" + sdk)
            replaced = True
        else:
            out.append(arg)
    if not replaced:
        out += ["-isysroot", sdk]
    return out


def _sdk_version(path):
    match = re.search(r"MacOSX(\d+(?:\.\d+)*)\.sdk/?$", path)
    return tuple(int(part) for part in match.group(1).split(".")) if match \
        else (0,)


def _candidate_sdks():
    roots = ["/Library/Developer/CommandLineTools/SDKs"]
    try:
        base = subprocess.run(["xcrun", "--show-sdk-path"],
                              stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                              text=True)
        if base.returncode == 0 and base.stdout.strip():
            roots.append(os.path.dirname(base.stdout.strip()))
    except OSError:
        pass
    found = set()
    for root in roots:
        found.update(glob.glob(os.path.join(root, "MacOSX*.sdk")))
    return sorted((path for path in found if _sdk_version(path) != (0,)),
                  key=_sdk_version, reverse=True)


def _std_usr_healthy(c_index_test, isysroot):
    """A libc++ newer than the clang that built c-index-test collapses `std::`
    types in USRs to the builtin `#I` encoding (dropping std::string DEFINITION
    USRs entirely). Probe with a std::string sentinel: the toolchain is healthy
    iff the sentinel's USR keeps the real `basic_string` mangling."""
    tmp = tempfile.mkdtemp(prefix="census_sdk_probe.")
    try:
        probe = os.path.join(tmp, "probe.cpp")
        with open(probe, "w", encoding="utf-8") as handle:
            handle.write("#include <string>\n"
                         "std::string __census_sdk_probe(std::string s) "
                         "{ return s; }\n")
        command = [c_index_test, "-test-load-source-usrs", "all", "-std=c++17"]
        if isysroot:
            command += ["-isysroot", isysroot]
        command.append(probe)
        proc = subprocess.run(command, stdout=subprocess.PIPE,
                              stderr=subprocess.PIPE, text=True)
        return any("@F@__census_sdk_probe" in line and "basic_string" in line
                   for line in proc.stdout.splitlines())
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def _compatible_isysroot(command):
    """The isysroot the census's clang/c-index-test should use so that `std::`
    types are not collapsed — or None to keep the compilation command's own.

    The census extracts USRs with the clang that built c-index-test. When the
    build was configured against a macOS SDK newer than that clang supports, the
    std::string DEFINITION USRs are dropped and the census cannot run at all (it
    is not merely a clearer error — B needs a runnable census to re-bank). Select
    the newest installed SDK whose libc++ keeps `std::` mangling intact so the
    census runs regardless of the build's SDK. Return None (keep the build SDK,
    and let the toolchain-degradation diagnostic fire) when none validates or the
    platform has no such mismatch (e.g. Linux)."""
    global _COMPATIBLE_ISYSROOT
    if _COMPATIBLE_ISYSROOT != "unset":
        return _COMPATIBLE_ISYSROOT
    _COMPATIBLE_ISYSROOT = None
    try:
        c_index_test = _c_index_test(command)
    except CensusError:
        return None
    current = _isysroot_of(command)
    if current is None or _std_usr_healthy(c_index_test, current):
        return None
    for sdk in _candidate_sdks():
        if sdk != current and _std_usr_healthy(c_index_test, sdk):
            _COMPATIBLE_ISYSROOT = sdk
            return sdk
    return None


def _command_for(rel, compdb):
    matches = [row for row in compdb
               if row.get("file", "").replace("\\", "/").endswith("/" + rel)]
    if len(matches) != 1:
        raise CensusError(
            f"{rel}: expected one compilation-database row, found {len(matches)}")
    row = matches[0]
    args = row.get("arguments") or shlex.split(row.get("command", ""))
    if not args:
        raise CensusError(f"{rel}: empty compilation command")
    original_source = os.path.abspath(row["file"])
    old_root = original_source[:-len(rel)]
    output = [args[0]]
    skip = False
    for arg in args[1:]:
        if skip:
            skip = False
            continue
        if arg in ("-o", "-MF", "-MT"):
            skip = True
            continue
        if arg in ("-c", "-MD") or os.path.abspath(arg) == original_source:
            continue
        if old_root and old_root in arg:
            arg = arg.replace(old_root.rstrip("/"), REPO)
        output.append(arg)
    output += [
        "-fsyntax-only", "-Xclang", "-ast-dump=json",
        "-Xclang", "-ast-dump-filter=neutrino", os.path.join(REPO, rel),
    ]
    # Extract USRs/AST with an SDK the c-index-test clang can parse, so a build
    # configured against a too-new macOS SDK does not collapse std:: types and
    # leave the census unrunnable (: B needs a runnable census to re-bank).
    compatible = _compatible_isysroot(output)
    if compatible:
        output = _with_isysroot(output, compatible)
    return output, row.get("directory") or REPO


def _ast(rel, compdb):
    command, cwd = _command_for(rel, compdb)
    proc = subprocess.run(
        command, cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
        text=True)
    if proc.returncode:
        raise CensusError(
            f"{rel}: Clang AST extraction failed:\n{proc.stderr[-3000:]}")
    roots = list(_json_stream(proc.stdout))
    if not roots:
        raise CensusError(f"{rel}: Clang AST extraction was empty")
    return roots


def _c_index_test(command):
    candidates = []
    located = shutil.which("c-index-test")
    if located:
        candidates.append(located)
    for arg in command:
        if arg.startswith("-I") and arg.endswith("/include"):
            candidates.append(os.path.join(
                os.path.dirname(arg[2:]), "bin", "c-index-test"))
    compiler_dir = os.path.dirname(command[0])
    candidates.append(os.path.join(compiler_dir, "c-index-test"))
    for candidate in candidates:
        if os.path.isfile(candidate) and os.access(candidate, os.X_OK):
            return candidate
    raise CensusError(
        "c-index-test is required to derive enclosing-symbol Clang USRs")


def _function_usrs(rel, compdb):
    command, cwd = _command_for(rel, compdb)
    compiler_args = []
    index = 1
    while index < len(command):
        if command[index] == "-Xclang":
            index += 2
            continue
        compiler_args.append(command[index])
        index += 1
    # -ferror-limit=0: c-index-test parses with a stock resource dir that emits
    # spurious diagnostics against the platform C++ stdlib headers; the default
    # error limit makes it STOP mid-parse (returncode still 0), silently
    # truncating the USR stream so later definitions — e.g. the  generated
    # renderer/builders included deep in the TU — get no USR. The real build
    # compiles the same TU cleanly; lift the limit so USR extraction is complete.
    proc = subprocess.run(
        [_c_index_test(command), "-test-load-source-usrs", "all",
         "-ferror-limit=0", *compiler_args],
        cwd=cwd, stdout=subprocess.PIPE, stderr=subprocess.PIPE, text=True)
    if proc.returncode:
        raise CensusError(
            f"{rel}: Clang USR extraction failed:\n{proc.stderr[-3000:]}")
    pattern = re.compile(
        r"^// CHECK: (?P<basename>\S+) (?P<usr>\S+) "
        r"Extent=\[(?P<line>\d+):\d+ - \d+:\d+\]$")
    rows = {}
    for line in proc.stdout.splitlines():
        match = pattern.match(line)
        if match and ("@F@" in match.group("usr")
                      or "@FT@" in match.group("usr")):
            rows.setdefault(match.group("basename"), []).append(
                (int(match.group("line")), match.group("usr")))
    if not rows:
        raise CensusError(f"{rel}: Clang USR extraction was empty")
    return rows


def _range(node):
    value = node.get("range", {})
    begin, end = value.get("begin", {}), value.get("end", {})
    if begin.get("offset") is None or end.get("offset") is None:
        return None
    return begin["offset"], end["offset"] + end.get("tokLen", 0)


def _normalized_tokens(text):
    token = re.compile(
        r'R"([^(\s]{0,16})\([\s\S]*?\)\1"|'
        r'"(?:\\.|[^"\\])*"|\'(?:\\.|[^\'\\])*\'|'
        r'[A-Za-z_]\w*|0[xX][0-9A-Fa-f]+|\d+(?:\.\d+)?|'
        r'::|->|<<|>>|<=|>=|==|!=|&&|\|\||\+\+|--|\+=|-=|'
        r'[^\s]')
    return " ".join(match.group(0) for match in token.finditer(text))


def _digest(text):
    return hashlib.sha256(_normalized_tokens(text).encode()).hexdigest()


def _effective_file(node, inherited):
    loc = node.get("loc", {})
    return loc.get("file", inherited)


def _usr_extraction_degraded(name, node, all_usrs):
    """True when c-index-test dropped this function's DEFINITION USR because the
    census toolchain SDK mismatched the clang that built c-index-test.

    Fingerprint: the AST shows a `std::` signature, yet the only USR carrying
    this function's name survives with its `std::` types collapsed away — no
    `@N@std@`/`basic_string` mangling, because a too-new libc++ makes clang emit
    the bare builtin `#I` encoding instead (e.g. clang-15 c-index-test against a
    macOS 26.x SDK drops every `std::string` out-of-line definition USR). This is
    a toolchain mismatch, NOT a missing/renamed symbol — reported distinctly so a
    genuine census gap (no such surviving name, or a non-`std::` signature) still
    fails closed with the ordinary per-symbol error.
    """
    qual = node.get("type", {}).get("qualType", "")
    if "std::" not in qual and "basic_string" not in qual:
        return False
    marker = "@F@" + name + "#"
    for rows in (all_usrs or {}).values():
        for _line, usr in rows:
            if marker in usr and "@N@std@" not in usr and "basic_string" not in usr:
                return True
    return False


def _projection_artifact_abspath(provider_basename):
    """Absolute path of the generated projection artifact (*Projection.inc) whose
    resolvers a given provider is authorized to include, or None if the basename is
    not a registered projection provider. Binds the  R5b resolver exemption to
    the EXACT committed artifact: a resolver with the same name reached from any
    other include (or handwritten in the provider) has a different origin file and
    stays governed as a declarative-recipe-candidate."""
    for spec in PROJECTION_ARTIFACTS:
        if os.path.basename(spec["provider"]) == provider_basename:
            return _abspath(spec["artifact"])
    return None


def _function_nodes(roots, source_abs, source, usr_rows, all_usrs=None):
    rows = []
    # Running document-order origin file. Clang omits `loc.file` when a node's file
    # matches the previous node in the serialized dump, so a fragment included from
    # a generated .inc carries the .inc path only on its FIRST node; the rest
    # inherit it in stream order. Tracking the last explicit file across the visit
    # reconstructs each node's TRUE origin file — used to bind the generated-resolver
    # exemptions to their exact artifact rather than to a mere "came from an include"
    # signal (which any unrelated included header would also satisfy).
    origin = {"file": None}

    def visit(node, inherited=None, scopes=()):
        loc_file = node.get("loc", {}).get("file")
        if loc_file:
            origin["file"] = loc_file
        current_file = _effective_file(node, inherited)
        kind = node.get("kind")
        next_scopes = scopes
        if kind in ("NamespaceDecl", "RecordDecl", "CXXRecordDecl") \
                and node.get("name"):
            next_scopes = scopes + (node["name"],)
        if (kind in ("FunctionDecl", "CXXMethodDecl", "FunctionTemplateDecl")
                and not node.get("isImplicit")
                and current_file == source_abs and _range(node)):
            # Clang reports a declaration from an included generated fragment
            # against the including source when the fragment location has no
            # explicit `file`. Admit only exact method spellings from the two
            # full-byte-regenerated Emit artifacts; a handwritten definition
            # has no `includedFrom` provenance and remains governed.
            if os.path.basename(source_abs) in {
                        "SolidityTargetAdapter.h",
                        "SolidityTargetAdapter.cpp"} and \
                    node.get("loc", {}).get("includedFrom") and \
                    node.get("name") in _fresh_generated_emit_builder_symbols():
                return
            #  R5b: the same rule for the generated finalized-view projection
            # resolvers a provider includes from its authenticated *Projection.inc
            # (project/slotExtent/slotItemOrder). Admit only a fresh, registered
            # resolver spelling whose TRUE origin file is the EXACT registered
            # artifact for this provider — not merely "reached from some include".
            # A handwritten projection in the provider (origin == the provider), or
            # a same-named resolver reached from any other included header (origin
            # == that header), fails the artifact match and stays governed.
            projection = _fresh_generated_projection_symbols()
            base_name = os.path.basename(source_abs)
            if base_name in projection and \
                    origin["file"] == _projection_artifact_abspath(base_name) and \
                    node.get("name") in projection[base_name]:
                return
            body = next((child for child in node.get("inner", [])
                         if child.get("kind") == "CompoundStmt"), None)
            if body is not None:
                display = "::".join(
                    next_scopes + (node.get("name", "<anonymous>"),))
                span = _range(node)
                start_line = source.count(b"\n", 0, span[0]) + 1
                marker = "@F@" + node.get("name", "<anonymous>")
                candidates = [
                    usr for line, usr in usr_rows
                    if (
                        (line == start_line and marker in usr)
                        or (
                            "@FT@" in usr
                            and line in (start_line, start_line - 1)
                            and node.get("name", "<anonymous>") in usr
                        )
                    )
                ]
                if candidates:
                    shortest = min(map(len, candidates))
                    candidates = [
                        candidate for candidate in candidates
                        if len(candidate) == shortest
                    ]
                if len(candidates) != 1:
                    if len(candidates) == 0 and _usr_extraction_degraded(
                            node.get("name", ""), node, all_usrs):
                        raise CensusError(
                            f"{os.path.basename(source_abs)}:{start_line}: "
                            f"c-index-test produced no definition USR for "
                            f"{display}, but a declaration USR for it survives "
                            f"with its std:: types collapsed to the builtin "
                            f"'#I' encoding — the census toolchain SDK does not "
                            f"match the clang that built c-index-test (a newer "
                            f"libc++ drops std::string definition USRs). Align "
                            f"the census SDK (CMAKE_OSX_SYSROOT / SDKROOT) to "
                            f"the clang that built c-index-test, then re-run.")
                    raise CensusError(
                        f"{os.path.basename(source_abs)}:{start_line}: "
                        f"expected one Clang USR for {display}, "
                        f"found {len(candidates)}")
                rows.append((node, display, candidates[0]))
                return
        for child in node.get("inner", []):
            visit(child, current_file, next_scopes)

    for root in roots:
        visit(root)
    unique = {}
    for node, symbol, usr in rows:
        key = (_range(node), usr)
        unique[key] = (node, symbol, usr)
    return [unique[key] for key in sorted(unique)]


def _contains_type(node, types):
    values = []
    node_type = node.get("type", {})
    values += [node_type.get("qualType", ""),
               node_type.get("desugaredQualType", "")]
    ref = node.get("referencedDecl", {})
    values += [ref.get("type", {}).get("qualType", "")]
    return any(re.search(rf"\b{re.escape(t)}\b", value)
               for t in types for value in values)


def _subtree_contains_type(node, types):
    return _contains_type(node, types) or any(
        _subtree_contains_type(child, types)
        for child in node.get("inner", []))


def _member_name(node):
    for child in node.get("inner", []):
        if child.get("kind") == "MemberExpr":
            return child.get("name")
    return None


def _callee_name(node):
    stack = list(node.get("inner", []))
    while stack:
        item = stack.pop(0)
        ref = item.get("referencedDecl", {})
        if ref.get("kind") in ("FunctionDecl", "CXXMethodDecl") \
                and ref.get("name"):
            return ref["name"]
        stack[0:0] = item.get("inner", [])
    return _member_name(node)


def _direct_kind(node, types):
    kind = node.get("kind")
    if kind in ("CallExpr", "CXXConstructExpr") and _contains_type(node, types):
        return "target-node-construction"
    if kind == "CXXMemberCallExpr" and _member_name(node) in INSERT_MEMBERS:
        stack = list(node.get("inner", []))
        while stack:
            item = stack.pop()
            if (_contains_type(item, types)
                    and "vector" in item.get("type", {}).get("qualType", "")):
                return "ordered-insertion"
            stack.extend(item.get("inner", []))
    if kind == "ReturnStmt" and any(
            _subtree_contains_type(child, types)
            for child in node.get("inner", [])):
        return "bundle-return"
    if kind in ("CallExpr", "CXXMemberCallExpr") and any(
            _subtree_contains_type(child, types)
            for child in node.get("inner", [])[1:]):
        return "bundle-pass"
    return None


def _events(function, symbol, symbol_usr, source, types, security_vars):
    events = []

    def append_event(node, path, occurrence_kind, carveout_id=None):
        if symbol.endswith("rejectsAtConstructionForTest") and \
                node.get("range", {}).get("begin", {}).get("includedFrom"):
            return
        span = _range(node)
        if not span or span[0] < 0 or span[1] > len(source):
            return
        snippet = source[span[0]:span[1]].decode(
            "utf-8", errors="replace")
        event = {
            "symbol": symbol,
            "symbolUsr": symbol_usr,
            "astKind": node["kind"],
            "astPath": "/".join(map(str, path)),
            "occurrenceKind": occurrence_kind,
            "offset": span[0],
            "endOffset": span[1],
            "line": source.count(b"\n", 0, span[0]) + 1,
            "callee": _callee_name(node),
            "tokenSha256": _digest(snippet),
        }
        if carveout_id:
            event["_carveoutId"] = carveout_id
        events.append(event)

    def visit(node, path):
        direct = _direct_kind(node, types)
        descendant_direct = False
        child_results = []
        for index, child in enumerate(node.get("inner", [])):
            result = visit(child, path + (index,))
            child_results.extend(result)
            descendant_direct = descendant_direct or bool(result)
        if direct:
            child_results.append((node, path, direct))
        elif node.get("kind") in CONTROL_KINDS and descendant_direct:
            child_results.append((node, path, CONTROL_KINDS[node["kind"]]))
        return child_results

    body = next(child for child in function.get("inner", [])
                if child.get("kind") == "CompoundStmt")
    for node, path, occurrence_kind in visit(body, ()):
        append_event(node, path, occurrence_kind)
    if symbol in GENERIC_DRIVER_SYMBOLS and not events:
        append_event(body, (), "generic-driver-function")

    def security_refs(node, path):
        if node.get("kind") == "DeclRefExpr":
            name = node.get("referencedDecl", {}).get("name")
            if name in security_vars:
                append_event(
                    node, path, "security-carveout-use",
                    security_vars[name])
        for index, child in enumerate(node.get("inner", [])):
            security_refs(child, path + (index,))

    security_refs(body, ())
    return events


def _exact_security_vars(roots, source_abs, registry):
    artifacts = {
        os.path.basename(entry["artifact"].split(" (", 1)[0]): entry["id"]
        for entry in registry["entries"]
        if entry["form"] == "exact-body"
        and source_abs.endswith(tuple(entry["allowedConsumers"]))
    }
    if not artifacts:
        return {}
    found = {}

    def visit(node, inherited=None):
        current_file = _effective_file(node, inherited)
        if node.get("kind") == "VarDecl" and current_file == source_abs:
            end_file = node.get("range", {}).get("end", {}).get("file", "")
            artifact_id = artifacts.get(os.path.basename(end_file))
            if artifact_id and node.get("name"):
                found[node["name"]] = artifact_id
        for child in node.get("inner", []):
            visit(child, current_file)

    for root in roots:
        visit(root)
    return found


def _security_regions():
    import importlib.util
    gate_path = os.path.join(
        REPO, "scripts/gates/check_security_primitive_carveout.py")
    spec = importlib.util.spec_from_file_location("_census_carveout", gate_path)
    gate = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(gate)
    gate.BUILD_DIR = BUILD_DIR
    registry = json.loads(_read(SECURITY_REGISTRY))
    gate.run_gate(registry, None)
    regions = []
    for entry in registry["entries"]:
        if entry["form"] != "reviewed-generator":
            continue
        rel, body = gate.site_region(entry, None)
        text = _read(rel)
        start = text.encode().find(body)
        if start < 0:
            raise CensusError(f"{entry['id']}: reviewed region not found")
        # Sources are ASCII in the governed regions, so byte/source offsets agree.
        regions.append((rel, start, start + len(body), entry["id"]))
    return regions


def _registered_source_role(rel):
    #  R1: a source may live in a structural subdir (provider/, harness/, …)
    # while its CMakeLists.txt stays at the backend root, and the CMake spells the
    # source path RELATIVE TO that root (e.g. `provider/SolidityRecipeProvider.cpp`,
    # or the bare basename for a flat backend). Walk up from the source's directory
    # to the nearest CMakeLists.txt and match the role by the source's path relative
    # to that CMakeLists directory.
    d = os.path.dirname(rel)
    while True:
        cmake_rel = os.path.join(d, "CMakeLists.txt")
        if os.path.isfile(os.path.join(REPO, cmake_rel)):
            break
        parent = os.path.dirname(d)
        if parent == d:
            return None
        d = parent
    spelled = os.path.relpath(rel, d)
    text = _read(cmake_rel)
    match = re.search(
        r"set_source_files_properties\(\s*" + re.escape(spelled) +
        r"\s+PROPERTIES\s+NEUTRINO_SEMANTIC_AUTHORITY_ROLE\s+"
        r"([A-Za-z0-9_-]+)\s*\)", text, re.S)
    return match.group(1) if match else None


def _llvm_tblgen():
    candidates = [
        os.environ.get("LLVM_TBLGEN"),
        shutil.which("llvm-tblgen"),
    ]
    brew = shutil.which("brew")
    if brew:
        prefix = subprocess.run(
            [brew, "--prefix", "llvm"], text=True,
            stdout=subprocess.PIPE, stderr=subprocess.DEVNULL)
        if prefix.returncode == 0:
            candidates.append(
                os.path.join(prefix.stdout.strip(), "bin", "llvm-tblgen"))
    for candidate in candidates:
        if candidate and os.path.isfile(candidate) \
                and os.access(candidate, os.X_OK):
            return candidate
    raise CensusError(
        "llvm-tblgen is required to authenticate generated builder bytes")


